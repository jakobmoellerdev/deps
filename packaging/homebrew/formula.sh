#!/usr/bin/env bash
# Prints the Homebrew formula of a release (Formula/deps.rb; the repository is its own tap) to stdout. It installs the
# release binary deps_<darwin|linux>_<amd64|arm64> as bin/deps with bash, zsh and fish completions.
#
#   formula.sh <tag> [checksums.txt]
#
# The sha256 sums come from checksums.txt (default: $DIST/checksums.txt, DIST default dist).
# RELEASE_URL is the download URL of the release's files (default: the Gitea release of <tag>).
set -euo pipefail

tag=${1:?usage: formula.sh <tag> [checksums.txt]}
checksums=${2:-${DIST:-dist}/checksums.txt}
url=${RELEASE_URL:-https://git.jakob-moeller.cloud/jakobmoellerdev/deps/releases/download/$tag}
version=${tag#v}
[[ $version =~ ^[0-9]+(\.[0-9]+)*(-[0-9A-Za-z.]+)?$ ]] || {
	echo "formula.sh: $tag is not a vX.Y.Z tag" >&2
	exit 1
}

# sum <file> prints the sha256 of a release file from checksums.txt.
sum() {
	local s
	s=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1; exit }' "$checksums")
	[[ $s =~ ^[0-9a-f]{64}$ ]] || {
		echo "formula.sh: no sha256 of $1 in $checksums" >&2
		return 1
	}
	echo "$s"
}

darwin_arm64=$(sum deps_darwin_arm64)
darwin_amd64=$(sum deps_darwin_amd64)
linux_arm64=$(sum deps_linux_arm64)
linux_amd64=$(sum deps_linux_amd64)

cat <<EOF
# Generated by packaging/homebrew/formula.sh in the deps release job; edits are overwritten.
class Deps < Formula
  desc "Renovate-style dependency update pull requests from one static binary"
  homepage "https://git.jakob-moeller.cloud/jakobmoellerdev/deps"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$url/deps_darwin_arm64"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$url/deps_darwin_amd64"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$url/deps_linux_arm64"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$url/deps_linux_amd64"
      sha256 "$linux_amd64"
    end
  end

  def install
    # The download is the bare binary, which Homebrew stages without the executable bit.
    binary = "deps_#{OS.mac? ? "darwin" : "linux"}_#{Hardware::CPU.arm? ? "arm64" : "amd64"}"
    chmod 0755, binary
    bin.install binary => "deps"
    generate_completions_from_executable(bin/"deps", "completion")
  end

  test do
    assert_equal "v#{version}", shell_output("#{bin}/deps version").strip
  end
end
EOF
