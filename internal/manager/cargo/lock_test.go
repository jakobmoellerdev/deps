// stub installs a fake cargo on PATH that logs its arguments and what it sees of the mirror,
// replaces Cargo.lock with STUB_LOCK on `update --workspace`, appends its arguments to it
// otherwise, and fails with STUB_FAIL set.
func stub(t *testing.T) (log string) {
	t.Helper()
	cp, err := exec.LookPath("cp")
	if err != nil {
		t.Skip("cp not in PATH")
	}
	bin := t.TempDir()
	log = filepath.Join(t.TempDir(), "log")
	script := `#!/bin/sh
echo "args: $*" >> "$STUB_LOG"
test -L src/lib.rs && echo "symlinked src/lib.rs" >> "$STUB_LOG"
test -L Cargo.toml || echo "copied Cargo.toml" >> "$STUB_LOG"
test -e target || test -e .git || echo "no target, no .git" >> "$STUB_LOG"
test -n "$STUB_FAIL" && { echo "warning: noise"; echo "error: boom in $(pwd)/Cargo.toml" >&2; exit 101; }
if [ "$*" = "update --workspace" ]; then
  test -n "$STUB_LOCK" && ` + cp + ` "$STUB_LOCK" Cargo.lock
else
  echo "# $*" >> Cargo.lock
fi
exit 0
`
	if err := os.WriteFile(filepath.Join(bin, "cargo"), []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", bin)
	t.Setenv("STUB_LOG", log)
	t.Setenv("STUB_FAIL", "")
	t.Setenv("STUB_LOCK", "")
	return log
}

func TestProcessStub(t *testing.T) {
	log := stub(t)
	dir := t.TempDir()
	before := lockOf("anyhow@1.0.80", "serde@1.0.228")
	write(t, dir, map[string]string{
		"Cargo.toml":          "[workspace]\nmembers = [\"crates/a\"]\n",
		"crates/a/Cargo.toml": "[dependencies]\nanyhow = \"1.0.80\"\nserde = \"1.0\"\n",
		"src/lib.rs":          "",
		"target/debug/x":      "",
		".git/HEAD":           "",
		"Cargo.lock":          "on disk, ignored",
	})
	resolved := filepath.Join(t.TempDir(), "resolved.lock")
	write(t, filepath.Dir(resolved), map[string]string{"resolved.lock": lockOf("anyhow@1.0.104", "serde@1.0.228")})
	t.Setenv("STUB_LOCK", resolved)

	patched := "[dependencies]\nanyhow = \"1.0.102\"\nserde = \"1.4\"\n"
	out, err := Locker{}.Process(t.Context(), dir, map[string][]byte{"crates/a/Cargo.toml": []byte(patched)}, map[string][]byte{"Cargo.lock": []byte(before)})
	if err != nil {
		t.Fatal(err)
	}
	want := lockOf("anyhow@1.0.104", "serde@1.0.228") + "# update --package anyhow@1.0.104 --precise 1.0.102\n"
	if got := string(out["Cargo.lock"]); got != want {
		t.Errorf("Cargo.lock:\n%s", got)
	}
	b, err := os.ReadFile(log)
	if err != nil {
		t.Fatal(err)
	}
	wantLog := "args: update --workspace\nsymlinked src/lib.rs\ncopied Cargo.toml\nno target, no .git\n" +
		"args: update --package anyhow@1.0.104 --precise 1.0.102\nsymlinked src/lib.rs\ncopied Cargo.toml\nno target, no .git\n"
	if string(b) != wantLog {
		t.Errorf("log:\n%s", b)
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "crates", "a", "Cargo.toml")); strings.Contains(string(b), "1.0.102") {
		t.Error("the working tree was modified")
	}
}

func TestProcessOutcomes(t *testing.T) {
	stub(t)
	dir := t.TempDir()
	write(t, dir, map[string]string{"Cargo.toml": "[dependencies]\nx = \"1\"\n"})
	manifests := map[string][]byte{"Cargo.toml": []byte("[dependencies]\nx = \"2\"\n")}
	lock := map[string][]byte{"Cargo.lock": []byte(lockOf("x@1.0.0"))}

	if out, err := (Locker{}).Process(t.Context(), dir, manifests, map[string][]byte{}); out != nil || err != nil {
		t.Errorf("without a lockfile: %v, %v", out, err)
	}
	if out, err := (Locker{}).Process(t.Context(), dir, manifests, lock); out != nil || err != nil {
		t.Errorf("unchanged lock: %v, %v", out, err)
	}
	t.Setenv("STUB_FAIL", "1")
	_, err := Locker{}.Process(t.Context(), dir, manifests, lock)
	if want := "cargo update in " + dir + ": warning: noise\nerror: boom in " + dir + "/Cargo.toml"; err == nil || err.Error() != want {
		t.Errorf("failure: %v", err)
	}
	t.Setenv("PATH", t.TempDir())
	if _, err := (Locker{}).Process(t.Context(), dir, manifests, lock); err == nil || err.Error() != "cargo not found (needed to update Cargo.lock)" {
		t.Errorf("missing cargo: %v", err)
	}
}

