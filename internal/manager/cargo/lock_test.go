func write(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for p, c := range files {
		abs := filepath.Join(dir, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(abs, []byte(c), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func TestScope(t *testing.T) {
	root := t.TempDir()
	write(t, root, map[string]string{
		"Cargo.toml":                 "[workspace]\nmembers = [\"crates/*\", \"tools/x\"]\nexclude = [\"crates/skip\"]\n",
		"Cargo.lock":                 "version = 4\n",
		"crates/a/Cargo.toml":        "",
		"crates/skip/Cargo.toml":     "",
		"other/Cargo.toml":           "",
		"tools/x/Cargo.toml":         "",
		"own/Cargo.toml":             "",
		"own/Cargo.lock":             "",
		"nolock/Cargo.toml":          "",
		"badws/Cargo.lock":           "",
		"badws/Cargo.toml":           "[workspace\n",
		"badws/m/Cargo.toml":         "",
		"lockless/Cargo.toml":        "",
		"lockless/member/Cargo.toml": "",
	})
	outside := t.TempDir()
	write(t, outside, map[string]string{"sub/Cargo.toml": "", "Cargo.toml": "[workspace]\nmembers = [\"sub\"]\n"})
	for manifest, want := range map[string]string{
		"Cargo.toml":             ".",
		"crates/a/Cargo.toml":    ".",
		"tools/x/Cargo.toml":     ".",
		"own/Cargo.toml":         "own",
		"crates/skip/Cargo.toml": "",
		"other/Cargo.toml":       "",
		"badws/m/Cargo.toml":     "",
	} {
		dir, ok := Locker{}.Scope(root, manifest)
		if dir != want || ok != (want != "") {
			t.Errorf("Scope(%s) = %q, %v, want %q", manifest, dir, ok, want)
		}
	}
	if dir, ok := (Locker{}).Scope(outside, "sub/Cargo.toml"); ok {
		t.Errorf("Scope without any Cargo.lock = %q", dir)
	}
	if dir, ok := (Locker{}).Scope(filepath.Join(root, "nolock"), "Cargo.toml"); ok {
		t.Errorf("Scope stops at the root: %q", dir)
	}
	if names := (Locker{}).Siblings(); len(names) != 1 || names[0] != "Cargo.lock" {
		t.Errorf("Siblings = %v", names)
	}
}

func TestCompatible(t *testing.T) {
	for _, tc := range []struct {
		a, b string
		want bool
	}{
		{"1.2.3", "1.9.0", true},
		{"1.2.3", "2.0.0", false},
		{"0.4.1", "0.4.9", true},
		{"0.4.1", "0.5.0", false},
		{"0.0.3", "0.0.3", true},
		{"0.0.3", "0.0.4", false},
	} {
		if got := compatible(semver.MustParse(tc.a), semver.MustParse(tc.b)); got != tc.want {
			t.Errorf("compatible(%s, %s) = %v", tc.a, tc.b, got)
		}
	}
}

func lockOf(pkgs ...string) string {
	var b strings.Builder
	b.WriteString("# This file is automatically @generated by Cargo.\nversion = 4\n")
	for _, p := range pkgs {
		name, version, _ := strings.Cut(p, "@")
		source := "\nsource = \"registry+https://github.com/rust-lang/crates.io-index\""
		if strings.HasPrefix(name, "git:") {
			name, source = name[4:], "\nsource = \"git+https://github.com/o/r?tag=v1#abc\""
		}
		fmt.Fprintf(&b, "\n[[package]]\nname = %q\nversion = %q%s\ndependencies = [\n \"x\",\n]\n", name, version, source)
	}
	return b.String()
}

func TestPrecise(t *testing.T) {
	before := lockOf("anyhow@1.0.80", "serde@1.0.228", "rand@0.8.5", "git:gitcrate@1.0.0", "dup@1.0.0")
	after := lockOf("anyhow@1.0.104", "serde@1.0.228", "rand@0.8.5", "rand@0.9.2", "git:gitcrate@2.0.0", "dup@1.5.0", "local@1.0.0")
	pins, err := precise([]byte(before), []byte(after), []crateUpdate{
		{"anyhow", "1.0.102"}, // cargo resolved a newer, not yet locked version: pinned down
		{"serde", "1.0.200"},  // 1.0.228 was locked before: never downgraded
		{"rand", "0.9.2"},     // exact match
		{"rand", "0.8"},       // partial: cargo's match stands
		{"gitcrate", "1.5.0"}, // not a registry package
		{"missing", "1.0.0"},  // not in the lock
		{"dup", "1.2.0"},      // pinned once,
		{"dup", "1.3.0"},      // a second target for the same entry is dropped
	})
	if err != nil {
		t.Fatal(err)
	}
	if got := fmt.Sprint(pins); got != "[{anyhow 1.0.104 1.0.102} {dup 1.5.0 1.2.0}]" {
		t.Errorf("pins = %s", got)
	}
	if _, err := precise([]byte("[[package\n"), []byte(after), nil); err == nil {
		t.Error("broken old lock accepted")
	}
	if _, err := precise([]byte(before), []byte("x = \"\n"), nil); err == nil {
		t.Error("broken new lock accepted")
	}
}

