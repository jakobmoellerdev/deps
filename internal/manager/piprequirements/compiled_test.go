func TestFileEdits(t *testing.T) {
	root := writeTree(t, compileTree)
	fe := New().(manager.FileEditor)
	deps := extractAll(t, root)
	in := map[string]dep.Dep{}
	for _, d := range deps["app/requirements.in"] {
		in[d.Name] = d
	}
	apply := func(edits map[string][]patch.Edit) string {
		var out []string
		for _, f := range slices.Sorted(func(yield func(string) bool) {
			for f := range edits {
				if !yield(f) {
					return
				}
			}
		}) {
			b, err := patch.Apply([]byte(compileTree[f]), edits[f])
			if err != nil {
				t.Fatal(err)
			}
			out = append(out, f+": "+strings.Join(pins(string(b)), " "))
		}
		return strings.Join(out, "; ")
	}
	for _, tt := range []struct {
		name string
		u    dep.Update
		want string
	}{
		{"exact pin", dep.Update{Dep: in["Flask"], NewVersion: "3.1.3"},
			"app/dev-requirements.txt: blinker==1.9.0 click==8.1.0 flask==3.1.3 requests==2.32.0; app/requirements.txt: blinker==1.9.0 flask==3.1.3 requests==2.32.3"},
		{"lockfile-only raises older pins", dep.Update{Dep: in["requests"], NewVersion: "2.32.5", Lockfile: true},
			"app/dev-requirements.txt: blinker==1.9.0 click==8.1.0 flask==3.1.0 requests==2.32.5; app/requirements.txt: blinker==1.9.0 flask==3.1.0 requests==2.32.5"},
		{"lockfile-only keeps newer pins", dep.Update{Dep: in["requests"], NewVersion: "2.32.1", Lockfile: true},
			"app/dev-requirements.txt: blinker==1.9.0 click==8.1.0 flask==3.1.0 requests==2.32.1"},
		{"not an input", dep.Update{Dep: deps["plain/requirements.txt"][0], NewVersion: "3.1.0"}, ""},
	} {
		t.Run(tt.name, func(t *testing.T) {
			edits, err := fe.FileEdits(root, tt.u)
			if err != nil {
				t.Fatal(err)
			}
			if got := apply(edits); got != tt.want {
				t.Errorf("got  %s\nwant %s", got, tt.want)
			}
			// fe answers every update of the run from one read and parse of each compiled
			// file; a manager that reads them anew must produce the same edits.
			fresh, err := New().(manager.FileEditor).FileEdits(root, tt.u)
			if err != nil {
				t.Fatal(err)
			}
			if got := apply(fresh); got != tt.want {
				t.Errorf("uncached got  %s\nwant %s", got, tt.want)
			}
			if !reflect.DeepEqual(edits, fresh) {
				t.Errorf("cached edits = %v, uncached = %v", edits, fresh)
			}
		})
	}
}

// pins returns the requirement lines of src.
func pins(src string) []string {
	var out []string
	for l := range strings.SplitSeq(src, "\n") {
		if l != "" && l[0] != '#' {
			out = append(out, l)
		}
	}
	return out
}

func TestLockRoots(t *testing.T) {
	root := writeTree(t, compileTree)
	var files []string
	for p := range compileTree {
		if match(p) {
			files = append(files, p)
		}
	}
	// py/requirements.txt is compiled from pyproject.toml, which re-running reads too.
	got := New().(manager.LockMaintainer).LockRoots(root, files)
	var lockfiles []string
	for _, lr := range got {
		if lr.Manifest != lr.Lockfile {
			t.Errorf("lock root %+v", lr)
		}
		lockfiles = append(lockfiles, lr.Lockfile)
	}
	want := []string{"app/dev-requirements.txt", "app/requirements.txt", "py/requirements.txt", "requirements.txt", "shared/requirements.txt", "shared/sub/requirements.txt"}
	if !slices.Equal(lockfiles, want) {
		t.Errorf("lock roots = %v, want %v", lockfiles, want)
	}
}

func TestHeaderBase(t *testing.T) {
	for _, c := range []struct {
		file, output, base, out string
		ok                      bool
	}{
		{"requirements.txt", "", ".", "requirements.txt", true},
		{"a/requirements.txt", "", "a", "requirements.txt", true},
		{"a/requirements.txt", "a/requirements.txt", ".", "a/requirements.txt", true},
		{"x/a/requirements.txt", "a/requirements.txt", "x", "a/requirements.txt", true},
		{"/abs/x/a/requirements.txt", "a/requirements.txt", "/abs/x", "a/requirements.txt", true},
		{"requirements.txt", "a/requirements.txt", "", "", false},
		{"a/requirements.txt", "other.txt", "", "", false},
	} {
		base, out, err := Header{Output: c.output}.Base(c.file)
		if (err == nil) != c.ok || base != c.base || out != c.out {
			t.Errorf("Base(%s, -o %s) = %q, %q, %v", c.file, c.output, base, out, err)
		}
	}
}

// TestOutputCache checks that an OutputCache answers the repeated lookups of a run, of the
// manager and of the post-processor, with what a scan returns, and that a nil one scans.
func TestOutputCache(t *testing.T) {
	root := writeTree(t, compileTree)
	c := NewOutputCache()
	var nilCache *OutputCache
	for range 2 {
		for _, input := range []string{"app/requirements.in", "app/base.in", "reqs/prod.in", "plain/requirements.txt", "missing.in"} {
			wantOuts, wantBase, wantOK := CompiledOutputs(root, input)
			for name, got := range map[string]func(string, string) ([]string, string, bool){"cached": c.Outputs, "nil": nilCache.Outputs} {
				outs, base, ok := got(root, input)
				if !slices.Equal(outs, wantOuts) || base != wantBase || ok != wantOK {
					t.Errorf("%s Outputs(%s) = %v, %q, %v; want %v, %q, %v", name, input, outs, base, ok, wantOuts, wantBase, wantOK)
				}
			}
		}
	}
}
