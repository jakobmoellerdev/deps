func pipHeader(args string) string {
	return "#\n# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n#    pip-compile " + args + "\n#\n"
}

// compileTree is a set of compiled files and inputs covering the graph rules.
var compileTree = map[string]string{
	// Two compiled files share requirements.in; dev.txt also includes base.in through dev.in.
	"app/requirements.in":  "Flask==3.1.0\nrequests>=2.31\n",
	"app/dev.in":           "-r requirements.in\n-r base.in\n",
	"app/base.in":          "click>=8\n",
	"app/requirements.txt": pipHeader("requirements.in") + "blinker==1.9.0\nflask==3.1.0\nrequests==2.32.3\n",
	"app/dev-requirements.txt": pipHeader("--output-file=dev-requirements.txt dev.in") +
		"blinker==1.9.0\nclick==8.1.0\nflask==3.1.0\nrequests==2.32.0\n",
	// The command ran in the root, its input is below.
	"requirements.txt": pipHeader("--output-file=requirements.txt reqs/prod.in") + "idna==3.10\nrequests==2.32.3\n",
	"reqs/prod.in":     "requests>=2\n",
	// Inputs the manager does not read: all pins stay requirements.
	"py/requirements.txt":    pipHeader("pyproject.toml") + "flask==3.1.0\n",
	"py/pyproject.toml":      "[project]\nname = \"x\"\n",
	"py/requirements.in":     "flask\n", // named by nothing that is handled
	"plain/requirements.txt": "flask==3.0.0\n",
	"MANIFEST.in":            "include README.md\n",
	// Compiled files sharing an input run in different directories: neither is handled.
	"shared/sub/requirements.txt": pipHeader("common.in") + "six==1.0\n",
	"shared/sub/common.in":        "six\n",
	"shared/requirements.txt":     pipHeader("sub/common.in") + "six==1.0\n",
}

func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for p, c := range files {
		abs := filepath.Join(root, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(abs, []byte(c), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// extractAll extracts and links the files of root as the engine does.
func extractAll(t *testing.T, root string) map[string][]dep.Dep {
	t.Helper()
	m := New()
	env := manager.Env{Exists: func(p string) bool {
		_, err := os.Stat(filepath.Join(root, filepath.FromSlash(p)))
		return err == nil
	}}
	var paths []string
	var files [][]dep.Dep
	for p := range compileTree {
		if !m.Match(p) {
			continue
		}
		src, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p)))
		if err != nil {
			t.Fatal(err)
		}
		deps, err := m.Extract(p, src, env)
		if err != nil {
			t.Fatal(err)
		}
		paths, files = append(paths, p), append(files, deps)
	}
	m.(manager.Linker).Link(files)
	out := map[string][]dep.Dep{}
	for i, p := range paths {
		out[p] = files[i]
	}
	return out
}

func TestLinkCompiled(t *testing.T) {
	root := writeTree(t, compileTree)
	got := map[string]string{}
	for p, deps := range extractAll(t, root) {
		var s []string
		for _, d := range deps {
			s = append(s, fmt.Sprintf("%s %s %s", d.DepType, d.Name, d.Locked))
		}
		got[p] = strings.Join(s, ", ")
	}
	for p, want := range map[string]string{
		"app/requirements.in":         "requirements Flask 3.1.0, requirements requests 2.32.0",
		"app/dev.in":                  "",
		"app/base.in":                 "requirements click 8.1.0",
		"app/requirements.txt":        "indirect blinker ",
		"app/dev-requirements.txt":    "indirect blinker ",
		"requirements.txt":            "indirect idna ",
		"reqs/prod.in":                "requirements requests 2.32.3",
		"py/requirements.txt":         "requirements flask ",
		"py/requirements.in":          "",
		"plain/requirements.txt":      "requirements flask ",
		"MANIFEST.in":                 "",
		"shared/sub/requirements.txt": "requirements six ",
		"shared/sub/common.in":        "",
		"shared/requirements.txt":     "requirements six ",
	} {
		if got[p] != strings.TrimSuffix(want, " ") && got[p] != want {
			t.Errorf("%s: %q, want %q", p, got[p], want)
		}
	}
}

