package piprequirements

import (
	"fmt"
	"strings"
	"testing"
)

// BenchmarkRefScanNewSource builds the source of a pip-compile file of 2000 hashed
// requirements behind a header.
func BenchmarkRefScanNewSource(b *testing.B) {
	var sb strings.Builder
	sb.WriteString("#\n# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n#    pip-compile --generate-hashes requirements.in\n#\n")
	sb.WriteString("--index-url https://pypi.org/simple\n-r base.txt\n-e ./local\n")
	for i := range 2000 {
		fmt.Fprintf(&sb, "pkg%d==1.%d.0 \\\n", i, i)
		for h := range 3 {
			fmt.Fprintf(&sb, "    --hash=sha256:%064x \\\n", i*3+h)
		}
		fmt.Fprintf(&sb, "    --hash=sha256:%064x\n    # via app\n", i)
	}
	src := []byte(sb.String())
	exists := func(string) bool { return true }
	b.ReportAllocs()
	for b.Loop() {
		newSource("requirements.txt", src, nil, exists)
	}
}
