// Header is the command in the header of a pip-compile or `uv pip compile` output file.
type Header struct {
	UV       bool
	Args     []string // after `pip-compile` / `uv pip compile`
	Output   string   // --output-file value; "" = none (stdout or pip-compile's default)
	Inputs   []string // positional arguments
	Files    []string // constraint, override and build-constraint files named by options
	CWDMoves bool     // --directory/--project: the command ran elsewhere
	Dropped  []bool   // args removed when re-running (--upgrade, existing --upgrade-package)
	Python   string   // pip-compile: the Python version (3.12) its marker names; "" = none
}

// ErrNotRegenerable is returned when the header command of a compiled file cannot be re-run
// from the repository: it ran elsewhere, wrote another file, or its inputs are missing.
var ErrNotRegenerable = errors.New("not regenerable")

// Header markers: pip-compile writes the command two lines below its marker, uv on the next.
const (
	pipCompileMarker = "autogenerated by pip-compile"
	uvCompileMarker  = "autogenerated by uv via the following command:"
)

// pipCompilePython matches the Python version pip-compile (pip-tools 6.6 and later) names in
// its marker line: "autogenerated by pip-compile with Python 3.12" ("python" before 7.0).
var pipCompilePython = regexp.MustCompile(`(?i)autogenerated by pip-compile with python (\d+\.\d+)\b`)

// valueOpts are the pip-compile and `uv pip compile` options that take a separate value.
var valueOpts = map[string]bool{
	"-o": true, "--output-file": true, "-i": true, "--index-url": true, "--extra-index-url": true,
	"--index": true, "--default-index": true, "-f": true, "--find-links": true, "-P": true,
	"--upgrade-package": true, "--pip-args": true, "-c": true, "--constraint": true,
	"--constraints": true, "--override": true, "--overrides": true, "-b": true,
	"--build-constraint": true, "--build-constraints": true, "--cache-dir": true,
	"--resolver": true, "--annotation-style": true, "--python-version": true,
	"--python-platform": true, "-p": true, "--python": true, "--python-executable": true,
	"--custom-compile-command": true, "--unsafe-package": true, "--no-emit-package": true,
	"--build-deps-for": true, "--extra": true, "--group": true, "--index-strategy": true,
	"--keyring-provider": true, "--prerelease": true, "--resolution": true,
	"--exclude-newer": true, "--exclude-newer-package": true, "--config-file": true,
	"--no-binary": true, "--only-binary": true, "--cert": true, "--client-cert": true,
	"--trusted-host": true, "--allow-insecure-host": true, "--max-rounds": true,
	"--refresh-package": true, "--reinstall-package": true, "--no-build-package": true,
	"--no-binary-package": true, "--fork-strategy": true, "--torch-backend": true,
	"--link-mode": true, "--color": true, "--directory": true, "--project": true,
	"-C": true, "--config-setting": true, "--config-settings": true, "--format": true,
	"--extra-build-dependencies": true,
}

// fileOpts are the options naming input files that are copied with the inputs.
var fileOpts = map[string]bool{
	"-c": true, "--constraint": true, "--constraints": true, "--override": true, "--overrides": true,
	"-b": true, "--build-constraint": true, "--build-constraints": true,
}

// ParseHeader parses the command of a pip-compile or `uv pip compile` header among the
// leading comment lines of src, with the Python version of a pip-compile marker.
func ParseHeader(src []byte) (Header, bool) {
	marker, python := false, ""
	for _, l := range headerLines(src) {
		text := strings.TrimSpace(strings.TrimPrefix(l, "#"))
		switch {
		case strings.Contains(text, pipCompileMarker) || strings.Contains(text, uvCompileMarker):
			marker = true
			if m := pipCompilePython.FindStringSubmatch(text); m != nil {
				python = m[1]
			}
		case !marker:
		case text == "pip-compile" || strings.HasPrefix(text, "pip-compile "):
			h, ok := parseArgs(false, strings.TrimPrefix(text, "pip-compile"))
			if ok {
				h.Python = python
			}
			return h, ok
		case strings.HasPrefix(text, "uv pip compile "):
			return parseArgs(true, strings.TrimPrefix(text, "uv pip compile"))
		}
	}
	return Header{}, false
}

// headerLines returns the leading `#` lines of src, each with its line break.
func headerLines(src []byte) []string {
	end := 0
	for end < len(src) && src[end] == '#' {
		i := bytes.IndexByte(src[end:], '\n')
		if i < 0 {
			end = len(src)
			break
		}
		end += i + 1
	}
	var out []string
	for rest := string(src[:end]); rest != ""; {
		l, r, ok := strings.Cut(rest, "\n")
		if ok {
			l += "\n"
		}
		out = append(out, l)
		rest = r
	}
	return out
}

// HeaderEnd returns the offset in src after its header's command line; 0 without one.
func HeaderEnd(src []byte) int {
	at, marker := 0, false
	for _, l := range headerLines(src) {
		at += len(l)
		text := strings.TrimSpace(strings.TrimPrefix(l, "#"))
		switch {
		case strings.Contains(text, pipCompileMarker) || strings.Contains(text, uvCompileMarker):
			marker = true
		case marker && (strings.HasPrefix(text, "pip-compile") || strings.HasPrefix(text, "uv pip compile")):
			return at
		}
	}
	return 0
}

func parseArgs(uv bool, line string) (Header, bool) {
	args, ok := splitShell(line)
	if !ok {
		return Header{}, false
	}
	h := Header{UV: uv, Args: args, Dropped: make([]bool, len(args))}
	for i := 0; i < len(args); i++ {
		a := args[i]
		if a == "-" {
			return Header{}, false // stdin
		}
		if !strings.HasPrefix(a, "-") {
			h.Inputs = append(h.Inputs, a)
			continue
		}
		opt, val, inline := strings.Cut(a, "=")
		if !inline && len(opt) > 2 && opt[1] != '-' && valueOpts[opt[:2]] { // -oFILE
			opt, val, inline = opt[:2], opt[2:], true
		}
		next := !inline && valueOpts[opt]
		if next {
			if i+1 >= len(args) {
				return Header{}, false
			}
			val = args[i+1]
		}
		switch {
		case opt == "-o" || opt == "--output-file":
			h.Output = val
		case opt == "--directory" || opt == "--project":
			h.CWDMoves = true
		case fileOpts[opt]:
			h.Files = append(h.Files, val)
		case opt == "-U" || opt == "--upgrade" || opt == "-P" || opt == "--upgrade-package":
			h.Dropped[i] = true
			if next {
				h.Dropped[i+1] = true
			}
		}
		if next {
			i++
		}
	}
	return h, true
}

// splitShell splits a POSIX shell command line into words (pip-compile quotes with
// shlex.quote).
func splitShell(s string) ([]string, bool) {
	var out []string
	var b strings.Builder
	word, quote := false, byte(0)
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case quote == '\'':
			if c == '\'' {
				quote = 0
			} else {
				b.WriteByte(c)
			}
		case quote == '"':
			switch {
			case c == '"':
				quote = 0
			case c == '\\' && i+1 < len(s) && strings.IndexByte("\"\\$`", s[i+1]) >= 0:
				i++
				b.WriteByte(s[i])
			default:
				b.WriteByte(c)
			}
		case c == '\'' || c == '"':
			quote, word = c, true
		case c == '\\' && i+1 < len(s):
			i++
			b.WriteByte(s[i])
			word = true
		case c == ' ' || c == '\t':
			if word {
				out = append(out, b.String())
				b.Reset()
				word = false
			}
		default:
			b.WriteByte(c)
			word = true
		}
	}
	if quote != 0 {
		return nil, false
	}
	if word {
		out = append(out, b.String())
	}
	return out, true
}

// Base returns the directory the header command ran in for the compiled file at the slash
// path file (relative or absolute): file's directory minus the directory of the
// --output-file path, and that path (the file relative to base). ErrNotRegenerable: the
// command ran elsewhere (--directory/--project) or wrote another file.
func (h Header) Base(file string) (base, out string, err error) {
	if h.CWDMoves {
		return "", "", fmt.Errorf("%w: --directory/--project", ErrNotRegenerable)
	}
	out = cmp.Or(h.Output, path.Base(file))
	if path.IsAbs(out) || filepath.IsAbs(out) {
		return "", "", fmt.Errorf("%w: absolute --output-file", ErrNotRegenerable)
	}
	out = path.Clean(filepath.ToSlash(out))
	if path.Base(out) != path.Base(file) || out == ".." || strings.HasPrefix(out, "../") {
		return "", "", fmt.Errorf("%w: --output-file %s is not this file", ErrNotRegenerable, h.Output)
	}
	fdir := path.Dir(file)
	switch sub := path.Dir(out); sub {
	case ".":
		return fdir, out, nil
	case fdir:
		return ".", out, nil
	default:
		trimmed, ok := strings.CutSuffix(fdir, "/"+sub)
		if !ok {
			return "", "", fmt.Errorf("%w: --output-file %s is not this file", ErrNotRegenerable, h.Output)
		}
		return trimmed, out, nil
	}
}

// Sources returns the input files of the command relative to its base: the positional
// arguments, else pip-compile's default source (setup.py when exists reports one in the base,
// else requirements.in). ErrNotRegenerable: a uv command without inputs.
func (h Header) Sources(exists func(name string) bool) ([]string, error) {
	inputs := h.Inputs
	if len(inputs) == 0 && !h.UV {
		inputs = []string{"requirements.in"}
		if exists("setup.py") {
			inputs = []string{"setup.py"}
		}
	}
	if len(inputs) == 0 {
		return nil, fmt.Errorf("%w: no input files", ErrNotRegenerable)
	}
	return inputs, nil
}

// Reference is a file a requirements file names: an included requirements file (`-r`), a
// constraints file (`-c`) or a local project (`-e ./dir`, `./dir`).
type Reference struct {
	Kind RefKind
	Path string // as written, relative to the requirements file's directory
}

// RefKind is the kind of a Reference.
type RefKind uint8

// Reference kinds.
const (
	RefRequirement RefKind = iota // -r, --requirement
	RefConstraint                 // -c, --constraint
	RefLocal                      // -e ./dir, ./dir
)

// References returns the files and local projects src names, in file order.
func References(src []byte) []Reference {
	var out []Reference
	for len(src) > 0 {
		line := src
		if i := bytes.IndexByte(src, '\n'); i >= 0 {
			line, src = src[:i], src[i+1:]
		} else {
			src = nil
		}
		if mayReference(line) {
			out = appendReference(out, string(line))
		}
	}
	return out
}

// mayReference reports whether line can name a Reference: its first word starts with
// `-r`, `-c`, `-e`, `--r`, `--c`, `--e` or `.`. Lines with a non-ASCII byte before the first
// word take the full path, which splits words on Unicode spaces.
func mayReference(line []byte) bool {
	i := 0
	for i < len(line) && asciiSpace(line[i]) {
		i++
	}
	if i == len(line) {
		return false
	}
	switch c := line[i]; {
	case c == '.' || c >= utf8.RuneSelf:
		return true
	case c != '-':
		return false
	}
	i++
	if i < len(line) && line[i] == '-' {
		i++
	}
	return i < len(line) && (line[i] == 'r' || line[i] == 'c' || line[i] == 'e')
}

func asciiSpace(c byte) bool {
	return c == ' ' || c == '\t' || c == '\r' || c == '\v' || c == '\f'
}

// appendReference appends the Reference the requirements line l names, if any.
func appendReference(out []Reference, l string) []Reference {
	if i := strings.Index(l, " #"); i >= 0 {
		l = l[:i]
	}
	f := strings.Fields(l)
	if len(f) == 0 || strings.HasPrefix(f[0], "#") {
		return out
	}
	opt, val := f[0], ""
	switch o, v, inline := strings.Cut(opt, "="); {
	case inline && strings.HasPrefix(o, "--"):
		opt, val = o, v
	case len(opt) > 2 && opt[0] == '-' && opt[1] != '-': // -rfile
		opt, val = opt[:2], opt[2:]
	case len(f) > 1:
		val = f[1]
	}
	switch opt {
	case "-r", "--requirement":
		if val != "" {
			out = append(out, Reference{RefRequirement, val})
		}
	case "-c", "--constraint":
		if val != "" {
			out = append(out, Reference{RefConstraint, val})
		}
	case "-e", "--editable":
		if localPath(val) {
			out = append(out, Reference{RefLocal, val})
		}
	default:
		if localPath(opt) {
			out = append(out, Reference{RefLocal, opt})
		}
	}
	return out
}

// localPath reports whether a requirement is a local directory path.
func localPath(s string) bool {
	return s == "." || strings.HasPrefix(s, "./") || strings.HasPrefix(s, "../")
}
