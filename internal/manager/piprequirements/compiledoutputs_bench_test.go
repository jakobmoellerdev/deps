package piprequirements

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// compiledTree writes a tree of inputs and large hashed compiled files, in a directory below
// the root so that the scan of an input walks up to it.
func compiledTree(tb testing.TB, sets, pkgs int) string {
	tb.Helper()
	root := tb.TempDir()
	for s := range sets {
		var sb strings.Builder
		name := fmt.Sprintf("requirements-s%d", s)
		fmt.Fprintf(&sb, "#\n# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n#    pip-compile --generate-hashes %s.in\n#\n", name)
		for i := range pkgs {
			fmt.Fprintf(&sb, "pkg%d==1.%d.0 \\\n", i, i)
			for h := range 3 {
				fmt.Fprintf(&sb, "    --hash=sha256:%064x \\\n", i*3+h)
			}
			fmt.Fprintf(&sb, "    --hash=sha256:%064x\n    # via -r requirements/%s.in\n", i, name)
		}
		for p, content := range map[string]string{
			"requirements/" + name + ".in":  "pkg1\npkg2\n",
			"requirements/" + name + ".txt": sb.String(),
		} {
			abs := filepath.Join(root, filepath.FromSlash(p))
			if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
				tb.Fatal(err)
			}
			if err := os.WriteFile(abs, []byte(content), 0o600); err != nil {
				tb.Fatal(err)
			}
		}
	}
	return root
}

// BenchmarkCompiledOutputs crawls a tree with one input and a large hashed compiled file.
func BenchmarkCompiledOutputs(b *testing.B) {
	root := compiledTree(b, 1, 2000)
	b.ReportAllocs()
	for b.Loop() {
		if outs, _, ok := CompiledOutputs(root, "requirements/requirements-s0.in"); !ok || len(outs) != 1 {
			b.Fatalf("CompiledOutputs = %v, %v", outs, ok)
		}
	}
}

// BenchmarkOutputCache looks the compiled files of the inputs of a tree up as a run does: once
// per update of a requirement of an input, and once more for the scope of each of its files.
func BenchmarkOutputCache(b *testing.B) {
	const sets = 4
	root := compiledTree(b, sets, 500)
	b.ReportAllocs()
	for b.Loop() {
		c := NewOutputCache()
		for range 10 {
			for s := range sets {
				in := fmt.Sprintf("requirements/requirements-s%d.in", s)
				if outs, _, ok := c.Outputs(root, in); !ok || len(outs) != 1 {
					b.Fatalf("Outputs = %v, %v", outs, ok)
				}
			}
		}
	}
}
