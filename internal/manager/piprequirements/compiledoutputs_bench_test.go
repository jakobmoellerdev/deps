package piprequirements

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// BenchmarkCompiledOutputs crawls a tree with one input and a large hashed compiled file.
func BenchmarkCompiledOutputs(b *testing.B) {
	root := b.TempDir()
	var sb strings.Builder
	sb.WriteString("#\n# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n#    pip-compile --generate-hashes requirements.in\n#\n")
	for i := range 2000 {
		fmt.Fprintf(&sb, "pkg%d==1.%d.0 \\\n", i, i)
		for h := range 3 {
			fmt.Fprintf(&sb, "    --hash=sha256:%064x \\\n", i*3+h)
		}
		fmt.Fprintf(&sb, "    --hash=sha256:%064x\n    # via -r requirements.in\n", i)
	}
	for name, content := range map[string]string{
		"requirements.in":  "pkg1\npkg2\n",
		"requirements.txt": sb.String(),
	} {
		if err := os.WriteFile(filepath.Join(root, name), []byte(content), 0o600); err != nil {
			b.Fatal(err)
		}
	}
	b.ReportAllocs()
	for b.Loop() {
		if outs, _, ok := CompiledOutputs(root, "requirements.in"); !ok || len(outs) != 1 {
			b.Fatalf("CompiledOutputs = %v, %v", outs, ok)
		}
	}
}
