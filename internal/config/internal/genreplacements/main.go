// Command genreplacements generates internal/config/replacements_gen.go, the built-in
// replacements, from Renovate's lib/data/replacements.json (vendored as
// internal/config/renovate-replacements.json; `task replacements:update` refreshes it).
//
// Only rules deps can apply are kept: datasources whose managers rename deps (docker,
// github-tags/github-releases for actions, npm, go, maven, terraform-provider, helm), a replacementName or a
// replacementNameTemplate of the form {{{replace '<prefix>' '<new prefix>' packageName}}}, and
// version matchers deps understands. Rules that remap versions (extractVersion, versioning)
// are left out. Every skipped rule is listed on stderr.
package main

import (
	"bytes"
	"encoding/json/jsontext"
	"encoding/json/v2"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/Masterminds/semver/v3"
)

// Paths relative to internal/config, where go:generate runs.
const (
	input  = "renovate-replacements.json"
	output = "replacements_gen.go"
)

func main() {
	src, err := os.ReadFile(input)
	if err != nil {
		fatal(err)
	}
	out, skipped, err := generate(src)
	if err != nil {
		fatal(err)
	}
	for _, s := range skipped {
		fmt.Fprintln(os.Stderr, "skipped:", s)
	}
	if err := os.WriteFile(output, out, 0o644); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "genreplacements:", err)
	os.Exit(1)
}

// managers are the deps managers that rename deps of a Renovate datasource.
var managers = map[string][]string{
	"docker":             {"docker", "gitlabci", "kustomize", "terraform"},
	"npm":                {"npm"},
	"github-tags":        {"github-actions"},
	"github-releases":    {"github-actions"},
	"go":                 {"gomod"},
	"maven":              {"maven", "gradle"},
	"terraform-provider": {"terraform"},
	"helm":               {"helm"},
}

type rule struct {
	MatchDatasources        []string `json:"matchDatasources"`
	MatchPackageNames       []string `json:"matchPackageNames"`
	MatchCurrentVersion     string   `json:"matchCurrentVersion"`
	MatchCurrentValue       string   `json:"matchCurrentValue"`
	ReplacementName         string   `json:"replacementName"`
	ReplacementNameTemplate string   `json:"replacementNameTemplate"`
	ReplacementVersion      string   `json:"replacementVersion"`
	ExtractVersion          string   `json:"extractVersion"`
	Versioning              string   `json:"versioning"`
}

type preset struct {
	PackageRules []rule `json:"packageRules"`
}

// templateRe is the one replacementNameTemplate form deps translates: a prefix replace.
var templateRe = regexp.MustCompile(`^\{{3}replace '([^']+)' '([^']+)' packageName\}{3}$`)

// generate returns the Go source of the built-in list and the rules it left out.
func generate(src []byte) ([]byte, []string, error) {
	var presets map[string]jsontext.Value
	if err := json.Unmarshal(src, &presets); err != nil {
		return nil, nil, err
	}
	names := make([]string, 0, len(presets))
	for n := range presets {
		if !strings.HasPrefix(n, "$") {
			names = append(names, n)
		}
	}
	slices.Sort(names)
	var b bytes.Buffer
	b.WriteString("// Code generated by genreplacements from renovate-replacements.json; DO NOT EDIT.\n\npackage config\n\n")
	b.WriteString("// Replacements is the built-in list: Renovate's replacements presets (lib/data/replacements.json)\n// that deps can apply, by preset name.\nvar Replacements = []Replacement{\n")
	var skipped []string
	for _, n := range names {
		var p preset
		if err := json.Unmarshal(presets[n], &p); err != nil {
			return nil, nil, fmt.Errorf("%s: %w", n, err)
		}
		for i, r := range p.PackageRules {
			entry, why := translate(r)
			if why != "" {
				if r.ReplacementName != "" || r.ReplacementNameTemplate != "" {
					skipped = append(skipped, fmt.Sprintf("%s[%d]: %s", n, i, why))
				}
				continue
			}
			fmt.Fprintf(&b, "\t{Name: %q, %s},\n", n, entry)
		}
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	return out, skipped, err
}

// translate renders the fields of r as a Replacement literal (after Name), or why it is left out.
func translate(r rule) (string, string) {
	var mgrs []string
	for _, ds := range r.MatchDatasources {
		for _, m := range managers[ds] {
			if !slices.Contains(mgrs, m) {
				mgrs = append(mgrs, m)
			}
		}
	}
	switch {
	case r.ReplacementName == "" && r.ReplacementNameTemplate == "":
		return "", "no replacement"
	case len(mgrs) == 0:
		return "", "datasources " + strings.Join(r.MatchDatasources, ",") + " not renamed by deps"
	case r.ExtractVersion != "" || r.Versioning != "":
		return "", "remaps versions"
	case len(r.MatchPackageNames) == 0:
		return "", "no package names"
	}
	var f []string
	f = append(f, "Managers: "+strList(mgrs))
	var globs, patterns []string
	for _, n := range r.MatchPackageNames {
		if len(n) > 1 && strings.HasPrefix(n, "/") && strings.HasSuffix(n, "/") {
			re := n[1 : len(n)-1]
			if _, err := regexp.Compile(re); err != nil {
				return "", "package pattern " + n + ": " + err.Error()
			}
			patterns = append(patterns, re)
		} else {
			globs = append(globs, n)
		}
	}
	if len(globs) > 0 {
		f = append(f, "Names: "+strList(globs))
	}
	if len(patterns) > 0 {
		f = append(f, "Patterns: "+strList(patterns))
	}
	switch cv := r.MatchCurrentVersion; {
	case cv != "" && r.MatchCurrentValue != "":
		return "", "matchCurrentVersion and matchCurrentValue"
	case cv != "":
		cv = mavenRange(cv)
		if _, err := semver.NewConstraint(cv); err != nil {
			return "", "matchCurrentVersion " + cv + ": " + err.Error()
		}
		f = append(f, "CurrentVersion: "+strconv.Quote(cv))
	case r.MatchCurrentValue != "":
		f = append(f, "CurrentVersion: "+strconv.Quote(r.MatchCurrentValue)) // the regex form /…/
	}
	if r.ReplacementNameTemplate != "" {
		m := templateRe.FindStringSubmatch(r.ReplacementNameTemplate)
		if m == nil {
			return "", "replacementNameTemplate " + r.ReplacementNameTemplate
		}
		prefix := strings.ReplaceAll(m[1], `\.`, ".")
		if regexp.QuoteMeta(prefix) != m[1] && prefix != m[1] {
			return "", "replacementNameTemplate pattern " + m[1]
		}
		f = append(f, "Prefix: "+strconv.Quote(prefix), "To: "+strconv.Quote(m[2]))
	} else {
		f = append(f, "To: "+strconv.Quote(r.ReplacementName))
	}
	if r.ReplacementVersion != "" {
		f = append(f, "Version: "+strconv.Quote(r.ReplacementVersion))
	}
	return strings.Join(f, ", "), ""
}

func strList(s []string) string {
	q := make([]string, len(s))
	for i, v := range s {
		q[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

// mavenRange converts a Maven version range ([3,4), (,2.0]) to a Masterminds constraint
// (>=3, <4); other values are returned unchanged.
func mavenRange(v string) string {
	if len(v) < 3 || !strings.ContainsAny(v[:1], "[(") || !strings.ContainsAny(v[len(v)-1:], "])") {
		return v
	}
	lo, hi, ok := strings.Cut(v[1:len(v)-1], ",")
	if !ok || strings.Contains(hi, ",") {
		return v
	}
	var c []string
	if lo = strings.TrimSpace(lo); lo != "" {
		c = append(c, map[byte]string{'[': ">=", '(': ">"}[v[0]]+lo)
	}
	if hi = strings.TrimSpace(hi); hi != "" {
		c = append(c, map[byte]string{']': "<=", ')': "<"}[v[len(v)-1]]+hi)
	}
	if len(c) == 0 {
		return v
	}
	return strings.Join(c, ", ")
}
