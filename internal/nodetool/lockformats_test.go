func TestMoveDescriptors(t *testing.T) {
	const head = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n"
	lock := head +
		"\"@s/a@1.2.0\":\n  version \"1.2.0\"\n\n" +
		"\"@s/a@^1.0.0\", \"@s/a@~1.1.0\":\n  version \"1.1.0\"\n\n" +
		"\"js-tokens@^3.0.0 || ^4.0.0\":\n  version \"4.0.0\"\n\n" +
		"z@2.0.1:\n  version \"2.0.1\"\n  dependencies:\n    \"@s/a\" \"^1.0.0\"\n\n" +
		"z@^2.0.0:\n  version \"2.0.0\"\n"
	got, err := moveDescriptors([]byte(lock), map[string][]dep.Update{
		"package.json":            {lockUp("dependencies", "@s/a", "^1.0.0", "1.2.0")},
		"packages/m/package.json": {lockUp("dependencies", "z", "^2.0.0", "2.0.1"), lockUp("dependencies", "@s/a", "^1.0.0", "1.2.0")},
	})
	// The shared entry keeps @s/a@~1.1.0, z@^2.0.0's entry goes away; unchanged headers stay.
	want := head +
		"\"@s/a@1.2.0\", \"@s/a@^1.0.0\":\n  version \"1.2.0\"\n\n" +
		"\"@s/a@~1.1.0\":\n  version \"1.1.0\"\n\n" +
		"\"js-tokens@^3.0.0 || ^4.0.0\":\n  version \"4.0.0\"\n\n" +
		"z@2.0.1, z@^2.0.0:\n  version \"2.0.1\"\n  dependencies:\n    \"@s/a\" \"^1.0.0\"\n"
	if err != nil || string(got) != want {
		t.Errorf("moveDescriptors =\n%s, %v\nwant\n%s", got, err, want)
	}
	// Already moved: nothing changes.
	if again, err := moveDescriptors(got, map[string][]dep.Update{"package.json": {lockUp("dependencies", "z", "^2.0.0", "2.0.1")}}); err != nil || string(again) != want {
		t.Errorf("moveDescriptors again =\n%s, %v", again, err)
	}
}

func TestYarnKey(t *testing.T) {
	for d, want := range map[string]string{
		"ms@^2.1.0":                  "ms@^2.1.0",
		"@s/a@~1.0.0":                `"@s/a@~1.0.0"`,
		"1x@1.0.0":                   `"1x@1.0.0"`,
		"trueish@1.0.0":              `"trueish@1.0.0"`,
		"falsey@1.0.0":               `"falsey@1.0.0"`,
		"falsy@1.0.0":                "falsy@1.0.0",
		"a@npm:b@1.0.0":              `"a@npm:b@1.0.0"`,
		"a@>= 1.0.0":                 `"a@>= 1.0.0"`,
		"js-tokens@^3.0.0 || ^4.0.0": `"js-tokens@^3.0.0 || ^4.0.0"`,
		"":                           `""`,
	} {
		if got := yarnKey(d); got != want {
			t.Errorf("yarnKey(%q) = %s, want %s", d, got, want)
		}
	}
}

func TestYarnVersions(t *testing.T) {
	lock := "__metadata:\n  version: 8\n\n\"a@npm:^1.0.0\":\n  versionx: 9\n  dependencies:\n    version: 7\n  version: 1.2.0\n\n# c\nb@^2.0.0:\n\n  version \"2.0.0\"\n"
	got, err := yarnVersions(strings.NewReader(lock), []lockWant{{name: "a", rng: "^1.0.0"}, {name: "b", rng: "^2.0.0"}, {name: "c"}})
	// b's version line follows a blank line: it belongs to no entry.
	if err != nil || strings.Join(got, ",") != "1.2.0,," {
		t.Errorf("yarnVersions = %q, %v", got, err)
	}
	if _, err := yarnVersions(strings.NewReader(strings.Repeat("x", 17<<20)), nil); err == nil {
		t.Error("overlong line: no error")
	}
}

func TestBunVersionsErrors(t *testing.T) {
	ws := []lockWant{{name: "a"}, {member: "m", name: "b"}}
	for src, want := range map[string]string{
		`[]`:                                  "want an object",
		`{"workspaces": []}`:                  "workspaces: ",
		`{"packages": []}`:                    "packages: want an object",
		`{"packages": {"a": []}}`:             `packages["a"]: want ["<name>@<version>", …]`,
		`{"packages": {"a": [1]}}`:            `packages["a"]: want ["<name>@<version>", …]`,
		`{"packages": {"a": ["a@1.0.0"] "b"}`: "jsontext: ",
		`{"lockfileVersion": 1, "x": {`:       "jsontext: ",
	} {
		if _, err := bunVersions(bufio.NewReader(strings.NewReader(src)), ws); err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("%s: err = %v, want %q", src, err, want)
		}
	}
	// A member without a name has no own entries; links and git dependencies are no versions.
	src := `{"workspaces": {"": {"name": "ws"}, "m": {},}, "packages": {"a": ["a@workspace:a"], "b": ["b@github:o/b#1"], "m/b": ["b@2.0.0"],},}`
	if got, err := bunVersions(bufio.NewReader(strings.NewReader(src)), ws); err != nil || strings.Join(got, ",") != "," {
		t.Errorf("bunVersions = %q, %v", got, err)
	}
}

func TestPnpmVersions(t *testing.T) {
	lock := "lockfileVersion: '9.0'\nimporters:\n  .:\n    dependencies:\n      a:\n        specifier: ^1.0.0\n        version: link:../a\n" +
		"      b:\n        specifier: npm:c@^1.0.0\n        version: c@1.2.0\n    optionalDependencies:\n      d: {specifier: ^1.0.0, version: 1.0.1}\n" +
		"packages:\n  a: [\n"
	got, err := pnpmVersions(bufio.NewReader(strings.NewReader(lock)), []lockWant{{name: "a"}, {name: "b"}, {name: "d"}, {member: "x", name: "d"}})
	if err != nil || strings.Join(got, ",") != ",,1.0.1," {
		t.Errorf("pnpmVersions = %q, %v", got, err)
	}
	if _, err := pnpmVersions(bufio.NewReader(strings.NewReader("importers:\n  .:\n    dependencies:\n      a: [1]\n")), []lockWant{{name: "a"}}); err == nil {
		t.Error("bad dependency: no error")
	}
	// A line longer than the reader's buffer is read in pieces.
	long := "lockfileVersion: '9.0'\n# " + strings.Repeat("x", 8<<10) + "\nimporters:\n  .:\n    dependencies:\n      a: {version: 1.0.0}\n"
	if got, err := pnpmVersions(bufio.NewReaderSize(strings.NewReader(long), 16), []lockWant{{name: "a"}}); err != nil || got[0] != "1.0.0" {
		t.Errorf("long line: %q, %v", got, err)
	}
}
