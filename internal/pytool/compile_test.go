// wheel writes a minimal pure-Python wheel of name and version to dir and returns its sha256.
func wheel(t *testing.T, dir, name, version string) string {
	t.Helper()
	p := filepath.Join(dir, name+"-"+version+"-py3-none-any.whl")
	f, err := os.Create(p)
	if err != nil {
		t.Fatal(err)
	}
	zw := zip.NewWriter(f)
	info := name + "-" + version + ".dist-info/"
	for n, body := range map[string]string{
		info + "METADATA": "Metadata-Version: 2.1\nName: " + name + "\nVersion: " + version + "\n",
		info + "WHEEL":    "Wheel-Version: 1.0\nGenerator: deps-test\nRoot-Is-Purelib: true\nTag: py3-none-any\n",
		info + "RECORD":   "",
	} {
		w, err := zw.Create(n)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := w.Write([]byte(body)); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

// TestCompilerRealUV regenerates a `uv pip compile --generate-hashes` file offline from a
// local directory of wheels (UV_FIND_LINKS: uv leaves --find-links out of the header).
func TestCompilerRealUV(t *testing.T) {
	uv, err := exec.LookPath("uv")
	if err != nil {
		t.Skip("uv not in PATH")
	}
	wheels, dir := t.TempDir(), t.TempDir()
	t.Setenv("UV_OFFLINE", "1")
	t.Setenv("UV_CACHE_DIR", t.TempDir())
	t.Setenv("UV_FIND_LINKS", wheels)
	wheel(t, wheels, "alpha", "1.0")
	a2 := wheel(t, wheels, "alpha", "2.0")
	beta := wheel(t, wheels, "beta", "1.0")
	write(t, dir, map[string]string{"requirements.in": "alpha\nbeta\n"})
	cmd := exec.CommandContext(t.Context(), uv, "pip", "compile", "--no-config", "--no-index",
		"--generate-hashes", "--output-file=requirements.txt", "requirements.in", "--upgrade-package", "alpha==1.0", "--no-progress", "-q")
	cmd.Dir = dir
	if b, err := cmd.CombinedOutput(); err != nil {
		t.Skipf("uv pip compile unavailable here: %v: %s", err, b)
	}
	orig := readFile(t, filepath.Join(dir, "requirements.txt"))
	if !strings.Contains(orig, "alpha==1.0 \\\n") {
		t.Fatalf("initial compile: %s", orig)
	}
	patched := strings.Replace(orig, "alpha==1.0", "alpha==2.0", 1)
	out, err := Compiler{}.Process(t.Context(), dir, bytesOf(map[string]string{"requirements.txt": patched}), nil)
	if err != nil {
		t.Fatal(err)
	}
	got := string(out["requirements.txt"])
	head := orig[:headerEnd([]byte(orig))]
	if !strings.HasPrefix(got, head) || !strings.Contains(got, "alpha==2.0 \\\n    --hash=sha256:"+a2+"\n") ||
		!strings.Contains(got, "beta==1.0 \\\n    --hash=sha256:"+beta+"\n") {
		t.Errorf("got %s", got)
	}
}
