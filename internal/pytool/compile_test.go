// sigstoreTree writes the sigstore fixtures into root/install with a root pyproject.toml and
// returns the original requirements.txt and a copy patched to sigstore 4.6.0.
func sigstoreTree(t *testing.T, root string) (orig, patched string) {
	t.Helper()
	orig = readFile(t, "testdata/sigstore/requirements.txt")
	write(t, root, map[string]string{
		"pyproject.toml":           "[project]\nname = \"sigstore\"\n",
		"README.md":                "not copied",
		"install/requirements.in":  readFile(t, "testdata/sigstore/requirements.in"),
		"install/requirements.txt": orig,
		"install/unrelated.txt":    "not copied",
	})
	return orig, strings.Replace(orig, "sigstore==4.5.1", "sigstore==4.6.0", 1)
}

func TestCompilerRegenerate(t *testing.T) {
	root := t.TempDir()
	_, patched := sigstoreTree(t, root)
	dir := filepath.Join(root, "install")
	t.Run("uv", func(t *testing.T) {
		log := stubs(t, "uv")
		out, err := Compiler{}.Process(t.Context(), dir, bytesOf(map[string]string{"requirements.txt": patched}), nil)
		if err != nil {
			t.Fatal(err)
		}
		if string(out["requirements.txt"]) != patched {
			t.Errorf("out = %q", out["requirements.txt"])
		}
		want := "argv: uv pip compile --no-config --universal --python-version 3.11 --generate-hashes --output-file=requirements.txt requirements.in --upgrade-package sigstore==4.6.0 --no-progress\n" +
			"env:  \nfile: ./requirements.in\nfile: ./requirements.txt\n"
		if got := readLog(t, log); got != want {
			t.Errorf("log = %q\nwant %q", got, want)
		}
	})
	t.Run("pip-compile through uvx with includes", func(t *testing.T) {
		root := t.TempDir()
		header := "#\n# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n" +
			"#    pip-compile --generate-hashes --output-file=sub/requirements.txt -c constraints.txt --upgrade sub/requirements.in\n#\n"
		write(t, root, map[string]string{
			"constraints.txt":      "x<3\n",
			"uv.toml":              "",
			"sub/requirements.in":  "-r base.in\n-e ./pkg  # local\nx\n",
			"sub/base.in":          "--constraint=more.txt\ny\n",
			"sub/more.txt":         "y<2\n",
			"sub/pkg/setup.py":     "",
			"sub/pkg/deep/x.py":    "not copied",
			"sub/requirements.txt": header + "x==1 \\\n    --hash=sha256:a\ny==1 \\\n    --hash=sha256:b\n",
		})
		// The header's Python version wins over a pip-compile in PATH, which runs with its own.
		log := stubs(t, "uvx", "pip-compile")
		patched := header + "x==2 \\\n    --hash=sha256:a\ny==1 \\\n    --hash=sha256:b\n"
		out, err := Compiler{}.Process(t.Context(), filepath.Join(root, "sub"), bytesOf(map[string]string{"requirements.txt": patched}), nil)
		if err != nil || string(out["requirements.txt"]) != patched {
			t.Fatalf("out = %q, %v", out, err)
		}
		want := "argv: uvx --python 3.12 --from pip-tools pip-compile --generate-hashes --output-file=sub/requirements.txt -c constraints.txt sub/requirements.in --upgrade-package x==2\n" +
			"env:  \nfile: ./constraints.txt\nfile: ./sub/base.in\nfile: ./sub/more.txt\nfile: ./sub/pkg/setup.py\nfile: ./sub/requirements.in\nfile: ./sub/requirements.txt\nfile: ./uv.toml\n"
		if got := readLog(t, log); got != want {
			t.Errorf("log = %q\nwant %q", got, want)
		}
	})
	t.Run("pip-compile in PATH without a Python version", func(t *testing.T) {
		root := t.TempDir()
		header := "#\n# This file is autogenerated by pip-compile\n# To update, run:\n#\n#    pip-compile --generate-hashes\n#\n"
		write(t, root, map[string]string{"requirements.in": "x\n", "requirements.txt": header + "x==1 \\\n    --hash=sha256:a\n"})
		log := stubs(t, "uvx", "pip-compile")
		patched := header + "x==2 \\\n    --hash=sha256:a\n"
		if _, err := (Compiler{}).Process(t.Context(), root, bytesOf(map[string]string{"requirements.txt": patched}), nil); err != nil {
			t.Fatal(err)
		}
		if got := readLog(t, log); !strings.HasPrefix(got, "argv: pip-compile --generate-hashes --output-file=requirements.txt --upgrade-package x==2\n") {
			t.Errorf("log = %q", got)
		}
	})
	t.Run("remote inputs stay URLs", func(t *testing.T) {
		root := t.TempDir()
		header := "#\n# This file is autogenerated by pip-compile\n# To update, run:\n#\n#    pip-compile -c https://example.com/c.txt requirements.in\n#\n"
		write(t, root, map[string]string{"requirements.in": "-r https://example.com/base.in\nx\n", "requirements.txt": header + "x==1\n"})
		log := stubs(t, "uvx", "pip-compile")
		patched := header + "x==2\n"
		if _, err := (Compiler{}).Process(t.Context(), root, bytesOf(map[string]string{"requirements.txt": patched}), nil); err != nil {
			t.Fatal(err)
		}
		if got := readLog(t, log); !strings.HasPrefix(got, "argv: pip-compile -c https://example.com/c.txt requirements.in --output-file=requirements.txt --upgrade-package x==2\n") {
			t.Errorf("log = %q", got)
		}
	})
	t.Run("not found", func(t *testing.T) {
		stubs(t)
		_, err := Compiler{}.Process(t.Context(), dir, bytesOf(map[string]string{"requirements.txt": patched}), nil)
		if err == nil || err.Error() != "uv not found (needed to regenerate requirements.txt)" {
			t.Errorf("err = %v", err)
		}
	})
	t.Run("failure", func(t *testing.T) {
		stubs(t, "uv")
		t.Setenv("STUB_FAIL", "1")
		_, err := Compiler{}.Process(t.Context(), dir, bytesOf(map[string]string{"requirements.txt": patched}), nil)
		if err == nil || !strings.HasSuffix(err.Error(), " in "+dir+": progress\nERR something broke") {
			t.Errorf("err = %v", err)
		}
	})
	// A resolution conflict cannot be fixed by a retry: the update is skipped. Other failures
	// stay errors (see failure).
	for tool, msg := range map[string]string{
		"uv":  "  × No solution found when resolving dependencies:\n  ╰─▶ Because you require sigstore==4.5.1 and sigstore==4.6.0, we can conclude that your requirements are unsatisfiable.",
		"uvx": "ERROR: Cannot install Flask==3.1.0 because these package versions have conflicting dependencies.\npip._internal.exceptions.DistributionNotFound: ResolutionImpossible: for help visit https://pip.pypa.io/en/latest/topics/dependency-resolution/#dealing-with-dependency-conflicts",
	} {
		t.Run("conflict "+tool, func(t *testing.T) {
			src, file := patched, "requirements.txt"
			if tool == "uvx" {
				src = "#\n# This file is autogenerated by pip-compile with Python 3.13\n# by the following command:\n#\n#    pip-compile --generate-hashes\n#\n" + patched[piprequirements.HeaderEnd([]byte(patched)):]
			}
			stubs(t, tool)
			t.Setenv("STUB_FAIL", "1")
			t.Setenv("STUB_FAIL_MSG", msg)
			_, err := Compiler{}.Process(t.Context(), dir, bytesOf(map[string]string{file: src}), nil)
			skip, ok := errors.AsType[*dep.SkipError](err)
			if !ok || skip.Reason != "conflicts with the inputs of requirements.txt (sigstore==4.6.0)" {
				t.Errorf("err = %v", err)
			}
		})
	}
	t.Run("failure is no skip", func(t *testing.T) {
		stubs(t, "uv")
		t.Setenv("STUB_FAIL", "1")
		t.Setenv("STUB_FAIL_MSG", "error: Failed to fetch: `https://pypi.org/simple/sigstore/`")
		_, err := Compiler{}.Process(t.Context(), dir, bytesOf(map[string]string{"requirements.txt": patched}), nil)
		if _, ok := errors.AsType[*dep.SkipError](err); ok || err == nil {
			t.Errorf("err = %v", err)
		}
	})
	t.Run("unchanged versions", func(t *testing.T) {
		stubs(t) // no tool runs
		orig := readFile(t, filepath.Join(dir, "requirements.txt"))
		out, err := Compiler{}.Process(t.Context(), dir, bytesOf(map[string]string{"requirements.txt": orig}), nil)
		if len(out) != 0 || err != nil {
			t.Errorf("out = %v, %v", out, err)
		}
	})
}

// TestCompilerRehash rewrites the hashes of a hand-maintained file, and of a compiled file
// whose header command cannot be re-run.
func TestCompilerRehash(t *testing.T) {
	a, b := strings.Repeat("a", 64), strings.Repeat("b", 64)
	src := readFile(t, "../manager/piprequirements/testdata/mypal68-flake8-requirements.txt")
	dir := t.TempDir()
	write(t, dir, map[string]string{"requirements.txt": src})
	patched := strings.Replace(strings.Replace(src, "autopep8==1.4.3", "autopep8==2.3.2", 1), "mccabe==0.6.1", "mccabe==0.7.0", 1)
	h := fakeHasher{"autopep8 2.3.2": {b, a}, "mccabe 0.7.0": {a}}
	out, err := Compiler{Hashes: h}.Process(t.Context(), dir, bytesOf(map[string]string{"requirements.txt": patched}), nil)
	if err != nil {
		t.Fatal(err)
	}
	want := strings.Replace(patched, "autopep8==2.3.2 \\\n    --hash=sha256:33d2b5325b7e1afb4240814fe982eea3a92ebea712869bfd08b3c0393404248c\n",
		"autopep8==2.3.2 \\\n    --hash=sha256:"+a+" \\\n    --hash=sha256:"+b+"\n", 1)
	want = strings.Replace(want, "mccabe==0.7.0 \\\n    --hash=sha256:ab8a6258860da4b6677da4bd2fe5dc2c659cff31b3ee4f7f5d64e79735b80d42 \\\n    --hash=sha256:dd8d182285a0fe56bace7f45b5e7d1a6ebcbf524e8f3bd87eb0f125271b8831f\n",
		"mccabe==0.7.0 \\\n    --hash=sha256:"+a+"\n", 1)
	if got := string(out["requirements.txt"]); got != want {
		t.Errorf("got %s", got)
	}

	t.Run("missing header input", func(t *testing.T) {
		root := t.TempDir()
		_, patched := sigstoreTree(t, root)
		if err := os.Remove(filepath.Join(root, "install", "requirements.in")); err != nil {
			t.Fatal(err)
		}
		out, err := Compiler{Hashes: fakeHasher{"sigstore 4.6.0": {a}}}.Process(t.Context(), filepath.Join(root, "install"), bytesOf(map[string]string{"requirements.txt": patched}), nil)
		if err != nil || !strings.Contains(string(out["requirements.txt"]), "sigstore==4.6.0 \\\n    --hash=sha256:"+a+"\n    # via") {
			t.Errorf("out = %s, %v", out["requirements.txt"], err)
		}
	})
	for name, c := range map[string]struct {
		hasher        Hasher
		orig, patched string
		err           string
	}{
		"no hasher":     {nil, "x==1 --hash=sha256:a\n", "x==2 --hash=sha256:a\n", "no hash source"},
		"lookup fails":  {fakeHasher{}, "x==1 --hash=sha256:a\n", "x==2 --hash=sha256:a\n", "hashes of x 2: no such release"},
		"edit fails":    {fakeHasher{"x 2": {a}}, "x==1 --hash=sha256:a -C k=v --hash=sha256:b\n", "x==2 --hash=sha256:a -C k=v --hash=sha256:b\n", "other options between"},
		"count changed": {nil, "x==1 --hash=sha256:a\n", "x==1 --hash=sha256:a\ny==1 --hash=sha256:b\n", "requirements changed from 1 to 2"},
		"name changed":  {nil, "x==1 --hash=sha256:a\n", "y==1 --hash=sha256:a\n", "requirement x became y"},
	} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			write(t, dir, map[string]string{"requirements.txt": c.orig})
			_, err := Compiler{Hashes: c.hasher}.Process(t.Context(), dir, bytesOf(map[string]string{"requirements.txt": c.patched}), nil)
			if err == nil || !strings.Contains(err.Error(), c.err) {
				t.Errorf("err = %v, want %q", err, c.err)
			}
		})
	}
	if _, err := (Compiler{}).Process(t.Context(), t.TempDir(), bytesOf(map[string]string{"requirements.txt": "x"}), nil); err == nil {
		t.Error("missing original accepted")
	}
}

