// fakeHasher returns hashes by "name version"; others fail.
type fakeHasher map[string][]string

func (f fakeHasher) Hashes(_ context.Context, d dep.Dep, version string) ([]string, error) {
	if h, ok := f[d.Name+" "+version]; ok {
		return h, nil
	}
	return nil, errors.New("no such release")
}

func readFile(t *testing.T, p string) string {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestParseHeader(t *testing.T) {
	sigstore := readFile(t, "testdata/sigstore/requirements.txt")
	for _, c := range []struct {
		name, src     string
		ok, uv        bool
		output        string
		inputs, files []string
		dropped       []string
	}{
		{"uv (sigstore)", sigstore, true, true, "requirements.txt", []string{"requirements.in"}, nil, nil},
		{"pip-compile", "#\n# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n" +
			"#    pip-compile --allow-unsafe --generate-hashes -o sub/requirements.txt -c 'con straints.txt' -P x --upgrade sub/requirements.in\n#\nx==1\n",
			true, false, "sub/requirements.txt", []string{"sub/requirements.in"}, []string{"con straints.txt"}, []string{"-P", "x", "--upgrade"}},
		{"pip-compile defaults", "# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n#    pip-compile\n",
			true, false, "", nil, nil, nil},
		{"short output option", "# This file was autogenerated by uv via the following command:\n#    uv pip compile -orequirements.txt \"a b.in\" --python=3.12\n",
			true, true, "requirements.txt", []string{"a b.in"}, nil, nil},
		{"custom compile command", "# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n#    make requirements\n", false, false, "", nil, nil, nil},
		{"stdin", "# This file was autogenerated by uv via the following command:\n#    uv pip compile -\n", false, true, "", nil, nil, nil},
		{"unterminated quote", "# This file was autogenerated by uv via the following command:\n#    uv pip compile 'x\n", false, true, "", nil, nil, nil},
		{"missing option value", "# This file was autogenerated by uv via the following command:\n#    uv pip compile x.in -o\n", false, true, "", nil, nil, nil},
		{"no header", "# pinned by hand\nx==1 --hash=sha256:abc\n", false, false, "", nil, nil, nil},
		{"command without marker", "#    uv pip compile x.in\n", false, false, "", nil, nil, nil},
	} {
		t.Run(c.name, func(t *testing.T) {
			cc, ok := parseHeader([]byte(c.src))
			if ok != c.ok {
				t.Fatalf("ok = %v", ok)
			}
			if !ok {
				return
			}
			var dropped []string
			for i, d := range cc.dropped {
				if d {
					dropped = append(dropped, cc.args[i])
				}
			}
			if cc.uv != c.uv || cc.output != c.output || !slices.Equal(cc.inputs, c.inputs) || !slices.Equal(cc.files, c.files) || !slices.Equal(dropped, c.dropped) {
				t.Errorf("got %+v", cc)
			}
		})
	}
	for src, want := range map[string]string{
		"# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n#    pip-compile\n": "3.12",
		"# This file is autogenerated by pip-compile with python 3.9\n# by the following command:\n#\n#    pip-compile\n":  "3.9",
		"# This file is autogenerated by pip-compile\n# To update, run:\n#\n#    pip-compile\n":                            "",
		"# This file was autogenerated by uv via the following command:\n#    uv pip compile x.in --python-version 3.11\n": "",
	} {
		if cc, ok := parseHeader([]byte(src)); !ok || cc.python != want {
			t.Errorf("python of %q = %q, %v; want %q", src, cc.python, ok, want)
		}
	}
	if got := headerEnd([]byte(sigstore)); !strings.HasPrefix(sigstore[got:], "annotated-types==") {
		t.Errorf("headerEnd = %d", got)
	}
	if got := headerEnd([]byte("# by hand\nx==1\n")); got != 0 {
		t.Errorf("headerEnd without header = %d", got)
	}
}

