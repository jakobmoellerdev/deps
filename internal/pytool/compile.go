// Hasher looks up the sha256 digests (lowercase hex) of the files of a release of d
// (pypi.Source.Hashes).
type Hasher interface {
	Hashes(ctx context.Context, d dep.Dep, version string) ([]string, error)
}

// Compiler is the post-processor (engine.PostProcessor) of the pip_requirements manager: it
// brings the `--hash` options of updated requirements in line with their new versions. A
// pip-compile or `uv pip compile` output file whose header command's inputs exist is
// regenerated by re-running that command in a temporary copy; in any other file the hashes
// of each updated requirement are replaced by those Hashes reports.
type Compiler struct{ Hashes Hasher }

// Scope returns the directory of a requirements file with `--hash` options.
func (Compiler) Scope(_ context.Context, root, manifest string) (string, bool) {
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(manifest)))
	if err != nil || !bytes.Contains(b, []byte("--hash")) {
		return "", false
	}
	return path.Dir(manifest), true
}

// Siblings is empty: inputs are named by each file's header.
func (Compiler) Siblings() []string { return nil }

// ScopeInputs implements engine.ScopeInputLister: for each manifest with a pip-compile or uv
// header whose command can be re-run, the files regenerate copies (collect: its inputs, the
// files they reference, constraint files, local projects' top-level files, uv.toml and
// pyproject.toml). The others are rehashed from the index alone and read nothing else.
func (Compiler) ScopeInputs(_ context.Context, root, dir string, manifests []string) (paths, digests []string, err error) {
	abs := filepath.Join(root, filepath.FromSlash(dir))
	for _, name := range manifests {
		src, err := os.ReadFile(filepath.Join(abs, filepath.FromSlash(name)))
		if err != nil {
			return nil, nil, err
		}
		cc, ok := parseHeader(src)
		if !ok {
			continue
		}
		base, out, files, err := cc.collect(abs, name, src)
		if errors.Is(err, errNotRegenerable) {
			continue // a missing input that appears is listed then
		}
		if err != nil {
			return nil, nil, err
		}
		rel, err := filepath.Rel(root, base)
		if err != nil {
			return nil, nil, err
		}
		for p := range files {
			if p != out {
				paths = append(paths, path.Join(filepath.ToSlash(rel), p))
			}
		}
	}
	return paths, nil, nil
}

// Process returns every patched requirements file in which a hashed requirement changed
// version, with its hashes updated.
func (c Compiler) Process(ctx context.Context, dir string, manifests, _ map[string][]byte) (map[string][]byte, error) {
	out := map[string][]byte{}
	for _, name := range slices.Sorted(maps.Keys(manifests)) {
		patched := manifests[name]
		orig, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
		if err != nil {
			return nil, err
		}
		changed, err := changedHashed(name, orig, patched)
		if err != nil {
			return nil, err
		}
		if len(changed) == 0 {
			continue
		}
		var b []byte
		cc, ok := parseHeader(patched)
		if ok {
			b, err = cc.regenerate(ctx, dir, name, patched, changed)
		}
		if !ok || errors.Is(err, errNotRegenerable) {
			if err != nil {
				slog.InfoContext(ctx, "rewriting hashes instead of regenerating", "file", filepath.Join(dir, name), "reason", err)
			}
			b, err = c.rehash(ctx, patched, changed)
		}
		if err != nil {
			return nil, err
		}
		out[name] = b
	}
	return out, nil
}

// changedHashed returns the hashed requirements of patched whose version differs from orig.
// Patching changes versions only, so both files have the same requirements in order.
func changedHashed(name string, orig, patched []byte) ([]piprequirements.Hashed, error) {
	olds := piprequirements.HashedRequirements(name, orig)
	news := piprequirements.HashedRequirements(name, patched)
	if len(olds) != len(news) {
		return nil, fmt.Errorf("%s: hashed requirements changed from %d to %d", name, len(olds), len(news))
	}
	var out []piprequirements.Hashed
	for i, n := range news {
		if n.Dep.Name != olds[i].Dep.Name {
			return nil, fmt.Errorf("%s: requirement %s became %s", name, olds[i].Dep.Name, n.Dep.Name)
		}
		if n.Dep.Version != olds[i].Dep.Version {
			out = append(out, n)
		}
	}
	return out, nil
}

// rehash replaces the hashes of each changed requirement by those of its new version.
func (c Compiler) rehash(ctx context.Context, src []byte, changed []piprequirements.Hashed) ([]byte, error) {
	if c.Hashes == nil {
		return nil, errors.New("no hash source for --hash requirements")
	}
	edits := make([]patch.Edit, 0, len(changed))
	for _, h := range changed {
		hashes, err := c.Hashes.Hashes(ctx, h.Dep, h.Dep.Version)
		if err != nil {
			return nil, fmt.Errorf("hashes of %s %s: %w", h.Dep.Name, h.Dep.Version, err)
		}
		e, err := piprequirements.HashEdit(src, h, hashes)
		if err != nil {
			return nil, err
		}
		edits = append(edits, e)
	}
	return patch.Apply(src, edits)
}

// compileCmd is the command in the header of a pip-compile or `uv pip compile` output file.
type compileCmd struct {
	uv       bool
	args     []string // after `pip-compile` / `uv pip compile`
	output   string   // --output-file value; "" = none (stdout or pip-compile's default)
	inputs   []string // positional arguments
	files    []string // constraint, override and build-constraint files named by options
	cwdMoves bool     // --directory/--project: the command ran elsewhere
	dropped  []bool   // args removed when re-running (--upgrade, existing --upgrade-package)
	python   string   // pip-compile: the Python version (3.12) its header names; "" = none
}

// Header markers: pip-compile writes the command two lines below its marker, uv on the next.
const (
	pipCompileMarker = "autogenerated by pip-compile"
	uvCompileMarker  = "autogenerated by uv via the following command:"
)

// pipCompilePython matches the Python version pip-compile (pip-tools 6.6 and later) names in
// its marker line: "autogenerated by pip-compile with Python 3.12" ("python" before 7.0).
var pipCompilePython = regexp.MustCompile(`(?i)autogenerated by pip-compile with python (\d+\.\d+)\b`)

// valueOpts are the pip-compile and `uv pip compile` options that take a separate value.
var valueOpts = map[string]bool{
	"-o": true, "--output-file": true, "-i": true, "--index-url": true, "--extra-index-url": true,
	"--index": true, "--default-index": true, "-f": true, "--find-links": true, "-P": true,
	"--upgrade-package": true, "--pip-args": true, "-c": true, "--constraint": true,
	"--constraints": true, "--override": true, "--overrides": true, "-b": true,
	"--build-constraint": true, "--build-constraints": true, "--cache-dir": true,
	"--resolver": true, "--annotation-style": true, "--python-version": true,
	"--python-platform": true, "-p": true, "--python": true, "--python-executable": true,
	"--custom-compile-command": true, "--unsafe-package": true, "--no-emit-package": true,
	"--build-deps-for": true, "--extra": true, "--group": true, "--index-strategy": true,
	"--keyring-provider": true, "--prerelease": true, "--resolution": true,
	"--exclude-newer": true, "--exclude-newer-package": true, "--config-file": true,
	"--no-binary": true, "--only-binary": true, "--cert": true, "--client-cert": true,
	"--trusted-host": true, "--allow-insecure-host": true, "--max-rounds": true,
	"--refresh-package": true, "--reinstall-package": true, "--no-build-package": true,
	"--no-binary-package": true, "--fork-strategy": true, "--torch-backend": true,
	"--link-mode": true, "--color": true, "--directory": true, "--project": true,
	"-C": true, "--config-setting": true, "--config-settings": true, "--format": true,
	"--extra-build-dependencies": true,
}

// fileOpts are the options naming input files that are copied with the inputs.
var fileOpts = map[string]bool{
	"-c": true, "--constraint": true, "--constraints": true, "--override": true, "--overrides": true,
	"-b": true, "--build-constraint": true, "--build-constraints": true,
}

// parseHeader parses the command of a pip-compile or `uv pip compile` header among the
// leading comment lines of src, with the Python version of a pip-compile marker.
func parseHeader(src []byte) (compileCmd, bool) {
	marker, python := false, ""
	for _, l := range headerLines(src) {
		text := strings.TrimSpace(strings.TrimPrefix(l, "#"))
		switch {
		case strings.Contains(text, pipCompileMarker) || strings.Contains(text, uvCompileMarker):
			marker = true
			if m := pipCompilePython.FindStringSubmatch(text); m != nil {
				python = m[1]
			}
		case !marker:
		case text == "pip-compile" || strings.HasPrefix(text, "pip-compile "):
			c, ok := parseArgs(false, strings.TrimPrefix(text, "pip-compile"))
			if ok {
				c.python = python
			}
			return c, ok
		case strings.HasPrefix(text, "uv pip compile "):
			return parseArgs(true, strings.TrimPrefix(text, "uv pip compile"))
		}
	}
	return compileCmd{}, false
}

// headerLines returns the leading `#` lines of src, each with its line break.
func headerLines(src []byte) []string {
	var out []string
	for rest := string(src); strings.HasPrefix(rest, "#"); {
		l, r, ok := strings.Cut(rest, "\n")
		if ok {
			l += "\n"
		}
		out = append(out, l)
		rest = r
	}
	return out
}

// headerEnd returns the offset in src after its header's command line; 0 without one.
func headerEnd(src []byte) int {
	at, marker := 0, false
	for _, l := range headerLines(src) {
		at += len(l)
		text := strings.TrimSpace(strings.TrimPrefix(l, "#"))
		switch {
		case strings.Contains(text, pipCompileMarker) || strings.Contains(text, uvCompileMarker):
			marker = true
		case marker && (strings.HasPrefix(text, "pip-compile") || strings.HasPrefix(text, "uv pip compile")):
			return at
		}
	}
	return 0
}

func parseArgs(uv bool, line string) (compileCmd, bool) {
	args, ok := splitShell(line)
	if !ok {
		return compileCmd{}, false
	}
	c := compileCmd{uv: uv, args: args, dropped: make([]bool, len(args))}
	for i := 0; i < len(args); i++ {
		a := args[i]
		if a == "-" {
			return compileCmd{}, false // stdin
		}
		if !strings.HasPrefix(a, "-") {
			c.inputs = append(c.inputs, a)
			continue
		}
		opt, val, inline := strings.Cut(a, "=")
		if !inline && len(opt) > 2 && opt[1] != '-' && valueOpts[opt[:2]] { // -oFILE
			opt, val, inline = opt[:2], opt[2:], true
		}
		next := !inline && valueOpts[opt]
		if next {
			if i+1 >= len(args) {
				return compileCmd{}, false
			}
			val = args[i+1]
		}
		switch {
		case opt == "-o" || opt == "--output-file":
			c.output = val
		case opt == "--directory" || opt == "--project":
			c.cwdMoves = true
		case fileOpts[opt]:
			c.files = append(c.files, val)
		case opt == "-U" || opt == "--upgrade" || opt == "-P" || opt == "--upgrade-package":
			c.dropped[i] = true
			if next {
				c.dropped[i+1] = true
			}
		}
		if next {
			i++
		}
	}
	return c, true
}

// splitShell splits a POSIX shell command line into words (pip-compile quotes with
// shlex.quote).
func splitShell(s string) ([]string, bool) {
	var out []string
	var b strings.Builder
	word, quote := false, byte(0)
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case quote == '\'':
			if c == '\'' {
				quote = 0
			} else {
				b.WriteByte(c)
			}
		case quote == '"':
			switch {
			case c == '"':
				quote = 0
			case c == '\\' && i+1 < len(s) && strings.IndexByte("\"\\$`", s[i+1]) >= 0:
				i++
				b.WriteByte(s[i])
			default:
				b.WriteByte(c)
			}
		case c == '\'' || c == '"':
			quote, word = c, true
		case c == '\\' && i+1 < len(s):
			i++
			b.WriteByte(s[i])
			word = true
		case c == ' ' || c == '\t':
			if word {
				out = append(out, b.String())
				b.Reset()
				word = false
			}
		default:
			b.WriteByte(c)
			word = true
		}
	}
	if quote != 0 {
		return nil, false
	}
	if word {
		out = append(out, b.String())
	}
	return out, true
}

// errNotRegenerable is returned when the inputs of a header command are not available.
var errNotRegenerable = errors.New("not regenerable")

// regenerate re-runs the header command for file name in dir in a temporary copy and returns
// the new file with the original header. errNotRegenerable: the inputs are not available. A
// resolution conflict (resolutionConflict) is a *dep.SkipError: the inputs do not admit the
// new versions, which no retry changes.
func (c compileCmd) regenerate(ctx context.Context, dir, name string, patched []byte, changed []piprequirements.Hashed) ([]byte, error) {
	base, out, files, err := c.collect(dir, name, patched)
	if errors.Is(err, errNotRegenerable) {
		return nil, fmt.Errorf("%s: cannot regenerate from its header command: %w", name, err)
	}
	if err != nil {
		return nil, err
	}
	tmp, err := os.MkdirTemp("", "deps-pip-compile-*")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmp)
	if err := toolrun.WriteFiles(tmp, files); err != nil {
		return nil, err
	}
	spec := c.spec(out, changed)
	if err := spec.run(ctx, tmp); err != nil {
		if errors.Is(err, exec.ErrNotFound) {
			return nil, fmt.Errorf("%s not found (needed to regenerate %s)", spec.tool, name)
		}
		if te, ok := errors.AsType[*toolError](err); ok && resolutionConflict(te.out) {
			slog.DebugContext(ctx, "requirements conflict", "file", filepath.Join(dir, name), "output", te.Error())
			return nil, &dep.SkipError{Reason: fmt.Sprintf("conflicts with the inputs of %s (%s)", name, strings.Join(upgradePins(changed), ", "))}
		}
		return nil, fmt.Errorf("%s in %s: %w", strings.Join(append([]string{spec.tool}, spec.args...), " "), base, err)
	}
	gen, err := os.ReadFile(filepath.Join(tmp, filepath.FromSlash(out)))
	if err != nil {
		return nil, err
	}
	head := patched[:headerEnd(patched)]
	return append(slices.Clip(head), gen[headerEnd(gen):]...), nil
}

// resolutionConflicts are the messages of pip (behind pip-compile) and uv for requirements
// that no set of versions satisfies. pip reports a version missing from the index otherwise
// ("No matching distribution found"); uv words both alike, but deps only asks for versions the
// index listed.
var resolutionConflicts = [][]byte{
	[]byte("ResolutionImpossible"),                          // pip
	[]byte("No solution found when resolving dependencies"), // uv
}

// resolutionConflict reports whether a compile command's output shows that the requested
// versions conflict with its inputs: a pin of the input file (`Flask==3.1.0` in requirements.in
// against flask 3.1.3), or another locked requirement's constraint on the dependency.
func resolutionConflict(out []byte) bool {
	return slices.ContainsFunc(resolutionConflicts, func(m []byte) bool { return bytes.Contains(out, m) })
}

// upgradePins are the sorted, distinct `<name>==<version>` pins of the changed requirements.
func upgradePins(changed []piprequirements.Hashed) []string {
	pins := make([]string, 0, len(changed))
	for _, h := range changed {
		pins = append(pins, h.Dep.Name+"=="+h.Dep.Version)
	}
	slices.Sort(pins)
	return slices.Compact(pins)
}

// spec is the command re-run in the copy: the header's arguments without upgrade options,
// an --output-file when the header had none, and `--upgrade-package <name>==<version>` per
// changed requirement. pip-compile runs with the Python version its header names (see
// cmdSpec.python): the output depends on it, and pins without wheels for another version fail
// to build (gevent 24.2.1 from a Python 3.12 header has no cp313 wheel).
func (c compileCmd) spec(out string, changed []piprequirements.Hashed) cmdSpec {
	var args []string
	if c.uv {
		args = append(args, "pip", "compile")
	}
	for i, a := range c.args {
		if !c.dropped[i] {
			args = append(args, a)
		}
	}
	if c.output == "" {
		args = append(args, "--output-file="+out)
	}
	for _, p := range upgradePins(changed) {
		args = append(args, "--upgrade-package", p)
	}
	if c.uv {
		return cmdSpec{tool: "uv", args: append(args, "--no-progress")}
	}
	return cmdSpec{tool: "pip-compile", args: args, uvx: true, from: "pip-tools", python: c.python}
}

// collect locates the directory the header command ran in (dir, or the ancestor that the
// --output-file path is relative to) and reads the files the command needs relative to it:
// the output file (patched), its inputs and the files named by `-r`/`-c` lines in them,
// constraint files of the command, the top-level files of local projects (a pyproject.toml
// or setup.py input, `-e ./dir`) and base's uv.toml and pyproject.toml (uv configuration).
// out is the output file relative to base.
func (c compileCmd) collect(dir, name string, patched []byte) (base, out string, files map[string][]byte, err error) {
	if c.cwdMoves {
		return "", "", nil, fmt.Errorf("%w: --directory/--project", errNotRegenerable)
	}
	out = cmp.Or(c.output, name)
	if path.IsAbs(out) || filepath.IsAbs(out) {
		return "", "", nil, fmt.Errorf("%w: absolute --output-file", errNotRegenerable)
	}
	out = path.Clean(filepath.ToSlash(out))
	if path.Base(out) != path.Base(name) || out == ".." || strings.HasPrefix(out, "../") {
		return "", "", nil, fmt.Errorf("%w: --output-file %s is not this file", errNotRegenerable, c.output)
	}
	base = dir
	if sub := path.Dir(out); sub != "." {
		trimmed, ok := strings.CutSuffix(filepath.ToSlash(dir), "/"+sub)
		if !ok {
			return "", "", nil, fmt.Errorf("%w: --output-file %s is not this file", errNotRegenerable, c.output)
		}
		base = filepath.FromSlash(trimmed)
	}
	inputs := c.inputs
	if len(inputs) == 0 && !c.uv { // pip-compile's default source
		inputs = []string{"requirements.in"}
		if isFile(filepath.Join(base, "setup.py")) {
			inputs = []string{"setup.py"}
		}
	}
	if len(inputs) == 0 {
		return "", "", nil, fmt.Errorf("%w: no input files", errNotRegenerable)
	}
	files = map[string][]byte{}
	for _, cfg := range []string{"uv.toml", Pyproject} {
		if b, err := os.ReadFile(filepath.Join(base, cfg)); err == nil {
			files[cfg] = b
		}
	}
	seen := map[string]bool{}
	for _, in := range slices.Concat(inputs, c.files) {
		if err := addInput(base, path.Clean(filepath.ToSlash(in)), files, seen); err != nil {
			return "", "", nil, err
		}
	}
	files[out] = patched
	return base, out, files, nil
}

// addInput reads the input rel (relative to base) into files, and for a requirements file
// the files and local projects its lines reference, relative to its directory.
func addInput(base, rel string, files map[string][]byte, seen map[string]bool) error {
	if seen[rel] || strings.Contains(rel, "://") {
		return nil
	}
	seen[rel] = true
	if path.IsAbs(rel) || rel == ".." || strings.HasPrefix(rel, "../") {
		return fmt.Errorf("%w: input %s outside %s", errNotRegenerable, rel, base)
	}
	abs := filepath.Join(base, filepath.FromSlash(rel))
	st, err := os.Stat(abs)
	if err != nil {
		return fmt.Errorf("%w: input %s: %w", errNotRegenerable, rel, err)
	}
	if st.IsDir() || slices.Contains([]string{Pyproject, "setup.py", "setup.cfg"}, path.Base(rel)) {
		pdir := rel
		if !st.IsDir() {
			pdir = path.Dir(rel)
		}
		top, err := topLevel(filepath.Join(base, filepath.FromSlash(pdir)))
		if err != nil {
			return err
		}
		for n, b := range top {
			files[path.Join(pdir, n)] = b
		}
		return nil
	}
	b, err := os.ReadFile(abs)
	if err != nil {
		return err
	}
	files[rel] = b
	for _, ref := range references(b) {
		if err := addInput(base, path.Join(path.Dir(rel), ref), files, seen); err != nil {
			return err
		}
	}
	return nil
}

// references returns the paths a requirements file names: `-r`/`-c` files and local
// projects (`-e ./dir`, `./dir`).
func references(src []byte) []string {
	var out []string
	for l := range strings.SplitSeq(string(src), "\n") {
		if i := strings.Index(l, " #"); i >= 0 {
			l = l[:i]
		}
		f := strings.Fields(l)
		if len(f) == 0 || strings.HasPrefix(f[0], "#") {
			continue
		}
		opt, val := f[0], ""
		switch o, v, inline := strings.Cut(opt, "="); {
		case inline && strings.HasPrefix(o, "--"):
			opt, val = o, v
		case len(opt) > 2 && opt[0] == '-' && opt[1] != '-': // -rfile
			opt, val = opt[:2], opt[2:]
		case len(f) > 1:
			val = f[1]
		}
		switch opt {
		case "-r", "--requirement", "-c", "--constraint":
			if val != "" {
				out = append(out, val)
			}
		case "-e", "--editable":
			if localPath(val) {
				out = append(out, val)
			}
		default:
			if localPath(opt) {
				out = append(out, opt)
			}
		}
	}
	return out
}

// localPath reports whether a requirement is a local directory path.
func localPath(s string) bool {
	return s == "." || strings.HasPrefix(s, "./") || strings.HasPrefix(s, "../")
}
