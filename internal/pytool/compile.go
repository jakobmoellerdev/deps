// Hasher looks up the sha256 digests (lowercase hex) of the files of a release of d
// (pypi.Source.Hashes).
type Hasher interface {
	Hashes(ctx context.Context, d dep.Dep, version string) ([]string, error)
}

// Compiler is the post-processor (engine.PostProcessor) of the pip_requirements manager. A
// pip-compile or `uv pip compile` output file whose header command's inputs exist is
// regenerated by re-running that command in a temporary copy, with the patched inputs of the
// scope, whenever one of its pins changed (the manager rewrites the pins of the compiled files
// of an updated input, piprequirements.FileEdits). In any other file the `--hash` options of
// each updated requirement are replaced by those Hashes reports. Outputs memoizes the scans
// for the compiled files of an input; without it every call scans again.
type Compiler struct {
	Hashes  Hasher
	Outputs *piprequirements.OutputCache
}

// Scope returns the directory a compiled file's header command runs in, for an input of
// compiled files (piprequirements.CompiledOutputs) theirs, so that both are post-processed
// together, and for any other requirements file with `--hash` options its own directory.
func (c Compiler) Scope(_ context.Context, root, manifest string) (string, bool) {
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(manifest)))
	if err != nil {
		return "", false
	}
	if h, ok := piprequirements.ParseHeader(b); ok {
		if base, _, err := h.Base(manifest); err == nil {
			return base, true
		}
	}
	if _, base, ok := c.Outputs.Outputs(root, manifest); ok {
		return base, true
	}
	if bytes.Contains(b, []byte("--hash")) {
		return path.Dir(manifest), true
	}
	return "", false
}

// Siblings is empty: inputs are named by each file's header, and the compiled files of an
// updated input are patched manifests of the scope.
func (Compiler) Siblings() []string { return nil }

// ScopeInputs implements engine.ScopeInputLister: for each manifest with a pip-compile or uv
// header whose command can be re-run, the files regenerate copies (collect: its inputs, the
// files they reference, constraint files, local projects' top-level files, uv.toml and
// pyproject.toml). The others are rehashed from the index alone and read nothing else.
func (Compiler) ScopeInputs(_ context.Context, root, dir string, manifests []string) (paths, digests []string, err error) {
	abs := filepath.Join(root, filepath.FromSlash(dir))
	for _, name := range manifests {
		src, err := os.ReadFile(filepath.Join(abs, filepath.FromSlash(name)))
		if err != nil {
			return nil, nil, err
		}
		h, ok := piprequirements.ParseHeader(src)
		if !ok {
			continue
		}
		base, out, files, err := compileCmd{h}.collect(abs, name, src, nil)
		if errors.Is(err, piprequirements.ErrNotRegenerable) {
			continue // a missing input that appears is listed then
		}
		if err != nil {
			return nil, nil, err
		}
		rel, err := filepath.Rel(root, base)
		if err != nil {
			return nil, nil, err
		}
		for p := range files {
			if p != out {
				paths = append(paths, path.Join(filepath.ToSlash(rel), p))
			}
		}
	}
	return paths, nil, nil
}

// Process returns every patched compiled file in which a requirement changed version,
// regenerated with `--upgrade-package <name>==<version>` per change, and every other patched
// requirements file in which a hashed requirement changed version, with its hashes updated.
// Inputs are copied as patched.
func (c Compiler) Process(ctx context.Context, dir string, manifests, _ map[string][]byte) (map[string][]byte, error) {
	out := map[string][]byte{}
	for _, name := range slices.Sorted(maps.Keys(manifests)) {
		patched := manifests[name]
		orig, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
		if err != nil {
			return nil, err
		}
		changed, err := changedPins(name, orig, patched)
		if err != nil {
			return nil, err
		}
		hashed := slices.DeleteFunc(slices.Clone(changed), func(h piprequirements.Hashed) bool { return len(h.Hashes) == 0 })
		h, compiled := piprequirements.ParseHeader(patched)
		if len(changed) == 0 || !compiled && len(hashed) == 0 {
			continue
		}
		var b []byte
		if compiled {
			b, err = compileCmd{h}.regenerate(ctx, dir, name, patched, upgradePins(changed), manifests)
		}
		if !compiled || errors.Is(err, piprequirements.ErrNotRegenerable) {
			if len(hashed) == 0 {
				slog.InfoContext(ctx, "keeping edited pins instead of regenerating", "file", filepath.Join(dir, name), "reason", err)
				continue
			}
			if err != nil {
				slog.InfoContext(ctx, "rewriting hashes instead of regenerating", "file", filepath.Join(dir, name), "reason", err)
			}
			b, err = c.rehash(ctx, patched, hashed)
		}
		if err != nil {
			return nil, err
		}
		out[name] = b
	}
	return out, nil
}

// ProcessLocked implements engine.LockfileUpdater: a lockfile-only update of an input's
// requirement keeps the input unchanged and rewrote the pins of its compiled files
// (piprequirements.FileEdits), which Process regenerates.
func (c Compiler) ProcessLocked(ctx context.Context, dir string, manifests, files map[string][]byte, _ map[string][]dep.Update) (map[string][]byte, error) {
	return c.Process(ctx, dir, manifests, files)
}

// MaintainManifests implements engine.ManifestMaintainer (lockFileMaintenance): each compiled
// file among manifests is regenerated by re-running its header command with `--upgrade`, so
// every pin moves to the newest version the inputs admit. It returns the files that changed.
func (Compiler) MaintainManifests(ctx context.Context, dir string, manifests, _ map[string][]byte) (map[string][]byte, error) {
	out := map[string][]byte{}
	for _, name := range slices.Sorted(maps.Keys(manifests)) {
		src := manifests[name]
		h, ok := piprequirements.ParseHeader(src)
		if !ok {
			continue
		}
		b, err := compileCmd{h}.regenerate(ctx, dir, name, src, nil, nil)
		if err != nil {
			return nil, err
		}
		if !bytes.Equal(b, src) {
			out[name] = b
		}
	}
	return out, nil
}

// changedPins returns the requirements of patched whose version differs from orig. Patching
// changes versions only, so both files have the same requirements in order.
func changedPins(name string, orig, patched []byte) ([]piprequirements.Hashed, error) {
	olds := piprequirements.Requirements(name, orig)
	news := piprequirements.Requirements(name, patched)
	if len(olds) != len(news) {
		return nil, fmt.Errorf("%s: requirements changed from %d to %d", name, len(olds), len(news))
	}
	var out []piprequirements.Hashed
	for i, n := range news {
		if n.Dep.Name != olds[i].Dep.Name {
			return nil, fmt.Errorf("%s: requirement %s became %s", name, olds[i].Dep.Name, n.Dep.Name)
		}
		if n.Dep.Version != olds[i].Dep.Version {
			out = append(out, n)
		}
	}
	return out, nil
}

// rehash replaces the hashes of each changed requirement by those of its new version.
func (c Compiler) rehash(ctx context.Context, src []byte, changed []piprequirements.Hashed) ([]byte, error) {
	if c.Hashes == nil {
		return nil, errors.New("no hash source for --hash requirements")
	}
	edits := make([]patch.Edit, 0, len(changed))
	for _, h := range changed {
		hashes, err := c.Hashes.Hashes(ctx, h.Dep, h.Dep.Version)
		if err != nil {
			return nil, fmt.Errorf("hashes of %s %s: %w", h.Dep.Name, h.Dep.Version, err)
		}
		e, err := piprequirements.HashEdit(src, h, hashes)
		if err != nil {
			return nil, err
		}
		edits = append(edits, e)
	}
	return patch.Apply(src, edits)
}

// compileCmd is the header command of a compiled requirements file.
type compileCmd struct{ piprequirements.Header }

// regenerate re-runs the header command for file name in dir in a temporary copy and returns
// the new file with the original header: with `--upgrade-package` per pin, or with
// `--upgrade` when pins is nil (lock file maintenance). overlay holds patched files by path
// relative to dir, copied instead of the files on disk. piprequirements.ErrNotRegenerable: the
// inputs are not available. A resolution conflict (resolutionConflict) of pins is a
// *dep.SkipError: the inputs do not admit the new versions, which no retry changes.
func (c compileCmd) regenerate(ctx context.Context, dir, name string, patched []byte, pins []string, overlay map[string][]byte) ([]byte, error) {
	base, out, files, err := c.collect(dir, name, patched, overlay)
	if errors.Is(err, piprequirements.ErrNotRegenerable) {
		return nil, fmt.Errorf("%s: cannot regenerate from its header command: %w", name, err)
	}
	if err != nil {
		return nil, err
	}
	tmp, err := os.MkdirTemp("", "deps-pip-compile-*")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmp)
	if err := toolrun.WriteFiles(tmp, files); err != nil {
		return nil, err
	}
	spec := c.spec(out, pins)
	if err := spec.run(ctx, tmp); err != nil {
		if errors.Is(err, exec.ErrNotFound) {
			return nil, fmt.Errorf("%s not found (needed to regenerate %s)", spec.tool, name)
		}
		if te, ok := errors.AsType[*toolError](err); ok && pins != nil && resolutionConflict(te.out) {
			slog.DebugContext(ctx, "requirements conflict", "file", filepath.Join(dir, name), "output", te.Error())
			return nil, &dep.SkipError{Reason: fmt.Sprintf("conflicts with the inputs of %s (%s)", name, strings.Join(pins, ", "))}
		}
		return nil, fmt.Errorf("%s in %s: %w", strings.Join(append([]string{spec.tool}, spec.args...), " "), base, err)
	}
	gen, err := os.ReadFile(filepath.Join(tmp, filepath.FromSlash(out)))
	if err != nil {
		return nil, err
	}
	head := patched[:piprequirements.HeaderEnd(patched)]
	return append(slices.Clip(head), gen[piprequirements.HeaderEnd(gen):]...), nil
}

// resolutionConflicts are the messages of pip (behind pip-compile) and uv for requirements
// that no set of versions satisfies. pip reports a version missing from the index otherwise
// ("No matching distribution found"); uv words both alike, but deps only asks for versions the
// index listed.
var resolutionConflicts = [][]byte{
	[]byte("ResolutionImpossible"),                          // pip
	[]byte("No solution found when resolving dependencies"), // uv
}

// resolutionConflict reports whether a compile command's output shows that the requested
// versions conflict with its inputs: another locked requirement's constraint on the
// dependency, or a pin of an input the update did not rewrite.
func resolutionConflict(out []byte) bool {
	return slices.ContainsFunc(resolutionConflicts, func(m []byte) bool { return bytes.Contains(out, m) })
}

// upgradePins are the sorted, distinct `<name>==<version>` pins of the changed requirements.
func upgradePins(changed []piprequirements.Hashed) []string {
	pins := make([]string, 0, len(changed))
	for _, h := range changed {
		pins = append(pins, h.Dep.Name+"=="+h.Dep.Version)
	}
	slices.Sort(pins)
	return slices.Compact(pins)
}

// spec is the command re-run in the copy: the header's arguments without upgrade options,
// an --output-file when the header had none, and `--upgrade-package <name>==<version>` per
// pin (`--upgrade` for nil pins). pip-compile runs with the Python version its header names
// (see cmdSpec.python): the output depends on it, and pins without wheels for another version
// fail to build (gevent 24.2.1 from a Python 3.12 header has no cp313 wheel).
func (c compileCmd) spec(out string, pins []string) cmdSpec {
	var args []string
	if c.UV {
		args = append(args, "pip", "compile")
	}
	for i, a := range c.Args {
		if !c.Dropped[i] {
			args = append(args, a)
		}
	}
	if c.Output == "" {
		args = append(args, "--output-file="+out)
	}
	if pins == nil {
		args = append(args, "--upgrade")
	}
	for _, p := range pins {
		args = append(args, "--upgrade-package", p)
	}
	if c.UV {
		return cmdSpec{tool: "uv", args: append(args, "--no-progress")}
	}
	return cmdSpec{tool: "pip-compile", args: args, uvx: true, from: "pip-tools", python: c.Python}
}

// collect locates the directory the header command of file name in dir ran in (base: the
// file's directory, or the ancestor that the --output-file path is relative to) and reads the
// files the command needs relative to it: the output file (patched), its inputs and the files
// named by `-r`/`-c` lines in them, constraint files of the command, the top-level files of
// local projects (a pyproject.toml or setup.py input, `-e ./dir`) and base's uv.toml and
// pyproject.toml (uv configuration). Files in overlay (by path relative to dir) are read from
// there. out is the output file relative to base.
func (c compileCmd) collect(dir, name string, patched []byte, overlay map[string][]byte) (base, out string, files map[string][]byte, err error) {
	b, out, err := c.Base(filepath.ToSlash(filepath.Join(dir, filepath.FromSlash(name))))
	if err != nil {
		return "", "", nil, err
	}
	base = filepath.FromSlash(b)
	inputs, err := c.Sources(func(n string) bool { return isFile(filepath.Join(base, n)) })
	if err != nil {
		return "", "", nil, err
	}
	over := make(map[string][]byte, len(overlay))
	for p, b := range overlay {
		over[filepath.Join(dir, filepath.FromSlash(p))] = b
	}
	files = map[string][]byte{}
	for _, cfg := range []string{"uv.toml", Pyproject} {
		if b, err := os.ReadFile(filepath.Join(base, cfg)); err == nil {
			files[cfg] = b
		}
	}
	in := inputSet{base: base, files: files, seen: map[string]bool{}, overlay: over}
	for _, f := range slices.Concat(inputs, c.Files) {
		if strings.Contains(f, "://") {
			continue // remote input: pip-compile fetches it itself
		}
		if err := in.add(path.Clean(filepath.ToSlash(f))); err != nil {
			return "", "", nil, err
		}
	}
	files[out] = patched
	return base, out, files, nil
}

// inputSet collects the input files of a compile command below base.
type inputSet struct {
	base    string
	files   map[string][]byte // by slash path relative to base
	seen    map[string]bool
	overlay map[string][]byte // patched files by absolute path
}

// add reads the input rel (relative to base) into files, and for a requirements file the
// files and local projects its lines reference, relative to its directory.
func (s inputSet) add(rel string) error {
	if s.seen[rel] {
		return nil
	}
	s.seen[rel] = true
	if path.IsAbs(rel) || rel == ".." || strings.HasPrefix(rel, "../") {
		return fmt.Errorf("%w: input %s outside %s", piprequirements.ErrNotRegenerable, rel, s.base)
	}
	abs := filepath.Join(s.base, filepath.FromSlash(rel))
	st, err := os.Stat(abs)
	if err != nil {
		return fmt.Errorf("%w: input %s: %w", piprequirements.ErrNotRegenerable, rel, err)
	}
	if st.IsDir() || slices.Contains([]string{Pyproject, "setup.py", "setup.cfg"}, path.Base(rel)) {
		pdir := rel
		if !st.IsDir() {
			pdir = path.Dir(rel)
		}
		top, err := topLevel(filepath.Join(s.base, filepath.FromSlash(pdir)))
		if err != nil {
			return err
		}
		for n, b := range top {
			s.files[path.Join(pdir, n)] = b
		}
		return nil
	}
	b, ok := s.overlay[abs]
	if !ok {
		if b, err = os.ReadFile(abs); err != nil {
			return err
		}
	}
	s.files[rel] = b
	for _, ref := range piprequirements.References(b) {
		if strings.Contains(ref.Path, "://") {
			continue
		}
		if err := s.add(path.Join(path.Dir(rel), ref.Path)); err != nil {
			return err
		}
	}
	return nil
}
