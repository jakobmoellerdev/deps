const uvHeader = "# This file was autogenerated by uv via the following command:\n#    uv pip compile requirements.in -o requirements.txt\n"

// compiledTree is a uv-compiled requirements.txt with its requirements.in, and a hand-written
// requirements file without header.
func compiledTree() map[string]string {
	return map[string]string{
		"app/requirements.in": "Flask==3.1.0\nrequests>=2.31\nclick\n",
		"app/requirements.txt": uvHeader + "blinker==1.9.0\n    # via flask\nclick==8.1.0\n    # via -r requirements.in\n" +
			"flask==3.1.0\n    # via -r requirements.in\nrequests==2.32.3\n    # via -r requirements.in\nurllib3==2.0.0\n    # via requests\n",
		"plain/requirements.txt": "flask==3.0.0\n",
	}
}

var compiledReleases = fakeGo{
	"Flask": {"3.1.0", "3.1.3"}, "flask": {"3.0.0", "3.1.0"}, "requests": {"2.32.3", "2.32.5"},
	"click": {"8.1.0", "8.2.0"}, "blinker": {"1.9.0", "1.9.1"}, "urllib3": {"2.0.0", "2.0.7", "2.5.0"},
}

func updateStrings(ups []dep.Update) []string {
	var out []string
	for _, u := range ups {
		from, to := u.FromTo()
		s := fmt.Sprintf("%s %s %s %s->%s", u.Dep.File, u.Dep.DepType, u.Dep.Name, from, to)
		if u.Lockfile {
			s += " lockfile"
		}
		if len(u.Advisories) > 0 {
			s += " security"
		}
		out = append(out, s)
	}
	return out
}

// The deps of a compiled requirements file come from its input: an exact pin is updated in
// the input, a range admitting the new version is a lockfile-only update, and pins no input
// names are indirect, ignored by default unless a rule opts them in or an advisory affects
// them. A file without compile header is unchanged.
func TestResolveCompiledRequirements(t *testing.T) {
	sec := &fakeSec{vulns: map[string][]Vuln{"urllib3": {vuln("GHSA-u", "2.0.7")}}}
	for _, tt := range []struct {
		name, cfg string
		sec       SecuritySource
		want      []string
		skips     []string
	}{
		{
			name: "defaults",
			want: []string{
				"app/requirements.in requirements Flask 3.1.0->3.1.3",
				"app/requirements.in requirements requests 2.32.3->2.32.5 lockfile",
				"plain/requirements.txt requirements flask 3.0.0->3.1.0",
			},
			skips: []string{
				"app/requirements.in click unconstrained",
				"app/requirements.txt blinker ignored by default (indirect; enable with a rule setting ignore: false)",
				"app/requirements.txt urllib3 ignored by default (indirect; enable with a rule setting ignore: false)",
			},
		},
		{
			name: "security fixes indirect pins", sec: sec,
			want: []string{
				"app/requirements.in requirements Flask 3.1.0->3.1.3",
				"app/requirements.in requirements requests 2.32.3->2.32.5 lockfile",
				"app/requirements.txt indirect urllib3 2.0.0->2.0.7 security",
				"plain/requirements.txt requirements flask 3.0.0->3.1.0",
			},
			skips: []string{
				"app/requirements.in click unconstrained",
				"app/requirements.txt blinker ignored by default (indirect; enable with a rule setting ignore: false)",
			},
		},
		{
			name: "a rule's ignore wins over security", sec: sec,
			cfg: "rules:\n  - names: [urllib3]\n    ignore: true\n",
			want: []string{
				"app/requirements.in requirements Flask 3.1.0->3.1.3",
				"app/requirements.in requirements requests 2.32.3->2.32.5 lockfile",
				"plain/requirements.txt requirements flask 3.0.0->3.1.0",
			},
			skips: []string{
				"app/requirements.in click unconstrained",
				"app/requirements.txt blinker ignored by default (indirect; enable with a rule setting ignore: false)",
				"app/requirements.txt urllib3 ignored by rule #0",
			},
		},
		{
			name: "indirect opted in",
			cfg:  "rules:\n  - manager: pip_requirements\n    depTypes: [indirect]\n    ignore: false\n    separateMajorMinor: false\n",
			want: []string{
				"app/requirements.in requirements Flask 3.1.0->3.1.3",
				"app/requirements.in requirements requests 2.32.3->2.32.5 lockfile",
				"app/requirements.txt indirect blinker 1.9.0->1.9.1",
				"app/requirements.txt indirect urllib3 2.0.0->2.5.0",
				"plain/requirements.txt requirements flask 3.0.0->3.1.0",
			},
			skips: []string{"app/requirements.in click unconstrained"},
		},
	} {
		t.Run(tt.name, func(t *testing.T) {
			root, cfg := setup(t, tt.cfg, compiledTree())
			o := Options{Managers: []manager.Manager{piprequirements.New()}, Datasources: map[string]Datasource{"pypi": compiledReleases}, Security: tt.sec}
			res, err := Resolve(t.Context(), root, cfg, env, o)
			if err != nil || len(res.Errors) > 0 {
				t.Fatal(err, res.Errors)
			}
			if got := updateStrings(res.Updates); !slices.Equal(got, tt.want) {
				t.Errorf("updates:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(tt.want, "\n"))
			}
			var skips []string
			for _, d := range res.Skipped {
				skips = append(skips, d.File+" "+d.Name+" "+d.Skip)
			}
			slices.Sort(skips)
			if !slices.Equal(skips, tt.skips) {
				t.Errorf("skips:\n%s\nwant:\n%s", strings.Join(skips, "\n"), strings.Join(tt.skips, "\n"))
			}
		})
	}
}

// An update of an input rewrites the pin of its compiled file too (plan shows both; apply and
// run regenerate the compiled file from them), and both files are inputs of its group.
func TestBuildCompiledRequirementsInput(t *testing.T) {
	root, cfg := setup(t, "", compiledTree())
	ms := []manager.Manager{piprequirements.New()}
	res, err := Resolve(t.Context(), root, cfg, env, Options{Managers: ms, Datasources: map[string]Datasource{"pypi": compiledReleases}})
	if err != nil || len(res.Errors) > 0 {
		t.Fatal(err, res.Errors)
	}
	byName := map[string]dep.Update{}
	for _, u := range res.Updates {
		byName[u.Dep.Name] = u
	}
	for name, want := range map[string]map[string]string{
		"Flask":    {"app/requirements.in": "Flask==3.1.3", "app/requirements.txt": "flask==3.1.3"},
		"requests": {"app/requirements.txt": "requests==2.32.5"}, // lockfile-only: the input keeps its range
	} {
		changes, errs := Build(t.Context(), root, ms, []dep.Update{byName[name]}, nil)
		if len(errs) > 0 {
			t.Fatal(errs)
		}
		var paths []string
		for _, c := range changes {
			paths = append(paths, c.Path)
			if !strings.Contains(string(c.New), want[c.Path]+"\n") {
				t.Errorf("%s: %s = %s", name, c.Path, c.New)
			}
		}
		if len(paths) != len(want) {
			t.Errorf("%s: changed %v, want %v", name, paths, want)
		}
	}
	ins, errs := Inputs(t.Context(), root, ms, map[string]PostProcessor{piprequirements.Name: pytool.Compiler{}}, [][]dep.Update{{byName["Flask"]}})
	if errs[0] != nil || !slices.Equal(ins[0].Paths, []string{"app/requirements.in", "app/requirements.txt"}) {
		t.Errorf("inputs = %+v, %v", ins, errs)
	}
}

// testWheel writes a minimal pure-Python wheel of name and version requiring requires.
func testWheel(t *testing.T, dir, name, version string, requires ...string) {
	t.Helper()
	f, err := os.Create(filepath.Join(dir, name+"-"+version+"-py3-none-any.whl"))
	if err != nil {
		t.Fatal(err)
	}
	zw := zip.NewWriter(f)
	info := name + "-" + version + ".dist-info/"
	meta := "Metadata-Version: 2.1\nName: " + name + "\nVersion: " + version + "\n"
	for _, r := range requires {
		meta += "Requires-Dist: " + r + "\n"
	}
	for n, body := range map[string]string{
		info + "METADATA": meta,
		info + "WHEEL":    "Wheel-Version: 1.0\nGenerator: deps-test\nRoot-Is-Purelib: true\nTag: py3-none-any\n",
		info + "RECORD":   "",
	} {
		w, err := zw.Create(n)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := w.Write([]byte(body)); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}
}

// pins returns the `name==version` lines of a compiled file, without hashes.
func pins(src []byte) []string {
	var out []string
	for l := range strings.SplitSeq(string(src), "\n") {
		if l != "" && l[0] != '#' && l[0] != ' ' {
			out = append(out, strings.TrimSuffix(l, " \\"))
		}
	}
	return out
}

// TestCompiledRequirementsRealUV runs the whole flow with `uv pip compile` offline from local
// wheels: requirements.txt is compiled from requirements.in, requirements-dev.txt from dev.in,
// which includes requirements.in. An exact pin update rewrites requirements.in and regenerates
// both compiled files, a range admits a lockfile-only update, a transitive pin gets a security
// update, and lock file maintenance moves every pin; each moves only its own packages.
func TestCompiledRequirementsRealUV(t *testing.T) {
	uv, err := exec.LookPath("uv")
	if err != nil {
		t.Skip("uv not in PATH")
	}
	wheels := t.TempDir()
	t.Setenv("UV_OFFLINE", "1")
	t.Setenv("UV_CACHE_DIR", t.TempDir())
	t.Setenv("UV_FIND_LINKS", wheels)
	testWheel(t, wheels, "alpha", "1.0")
	testWheel(t, wheels, "alpha", "2.0")
	testWheel(t, wheels, "beta", "1.0", "gamma")
	testWheel(t, wheels, "beta", "1.1", "gamma")
	testWheel(t, wheels, "gamma", "1.0")
	testWheel(t, wheels, "gamma", "1.1")
	testWheel(t, wheels, "delta", "1.0")
	root, cfg := setup(t, "lockFileMaintenance:\n  enabled: true\n", map[string]string{
		"py/requirements.in": "alpha==1.0\nbeta>=1.0\n",
		"py/dev.in":          "-r requirements.in\ndelta\n",
	})
	dir := filepath.Join(root, "py")
	for out, in := range map[string]string{"requirements.txt": "requirements.in", "requirements-dev.txt": "dev.in"} {
		cmd := exec.CommandContext(t.Context(), uv, "pip", "compile", "--no-config", "--no-index", "--generate-hashes",
			"--output-file="+out, in, "--upgrade-package", "beta==1.0", "--upgrade-package", "gamma==1.0", "--no-progress", "-q")
		cmd.Dir = dir
		if b, err := cmd.CombinedOutput(); err != nil {
			t.Skipf("uv pip compile unavailable here: %v: %s", err, b)
		}
	}
	orig := map[string][]byte{}
	for _, f := range []string{"requirements.in", "requirements.txt", "requirements-dev.txt"} {
		b, err := os.ReadFile(filepath.Join(dir, f))
		if err != nil {
			t.Fatal(err)
		}
		orig["py/"+f] = b
	}
	if got := pins(orig["py/requirements-dev.txt"]); !slices.Equal(got, []string{"alpha==1.0", "beta==1.0", "delta==1.0", "gamma==1.0"}) {
		t.Fatalf("initial compile: %q", got)
	}

	ms := []manager.Manager{piprequirements.New()}
	releases := fakeGo{"alpha": {"1.0", "2.0"}, "beta": {"1.0", "1.1"}, "gamma": {"1.0", "1.1"}, "delta": {"1.0"}}
	sec := &fakeSec{vulns: map[string][]Vuln{"gamma": {vuln("GHSA-g", "1.1")}}}
	res, err := Resolve(t.Context(), root, cfg, env, Options{Managers: ms, Datasources: map[string]Datasource{"pypi": releases}, Security: sec})
	if err != nil || len(res.Errors) > 0 {
		t.Fatal(err, res.Errors)
	}
	want := []string{
		" lockFileMaintenance py/requirements-dev.txt->",
		" lockFileMaintenance py/requirements.txt->",
		"py/requirements-dev.txt indirect gamma 1.0->1.1 security",
		"py/requirements.in requirements alpha 1.0->2.0",
		"py/requirements.in requirements beta 1.0->1.1 lockfile",
		"py/requirements.txt indirect gamma 1.0->1.1 security",
	}
	got := updateStrings(res.Updates)
	for i, u := range res.Updates {
		if u.Maintenance() {
			got[i] = " lockFileMaintenance " + u.Dep.Name + "->"
		}
	}
	slices.Sort(got)
	if !slices.Equal(got, want) {
		t.Fatalf("updates:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}

	post := map[string]PostProcessor{piprequirements.Name: pytool.Compiler{}}
	build := func(t *testing.T, ups []dep.Update) map[string][]byte {
		t.Helper()
		changes, errs := Build(t.Context(), root, ms, ups, post)
		if len(errs) > 0 {
			t.Fatal(errs)
		}
		out := map[string][]byte{}
		for _, c := range changes {
			out[c.Path] = c.New
		}
		return out
	}
	of := func(name string, maintenance bool) []dep.Update {
		var out []dep.Update
		for _, u := range res.Updates {
			if u.Dep.Name == name || maintenance && u.Maintenance() {
				out = append(out, u)
			}
		}
		return out
	}
	head := func(b []byte) string { return string(b[:piprequirements.HeaderEnd(b)]) }
	for _, tt := range []struct {
		name string
		ups  []dep.Update
		want map[string][]string // pins per changed compiled file
		in   string              // new requirements.in; "" = unchanged
	}{
		{"exact pin", of("alpha", false), map[string][]string{
			"py/requirements.txt":     {"alpha==2.0", "beta==1.0", "gamma==1.0"},
			"py/requirements-dev.txt": {"alpha==2.0", "beta==1.0", "delta==1.0", "gamma==1.0"},
		}, "alpha==2.0\nbeta>=1.0\n"},
		{"lockfile-only", of("beta", false), map[string][]string{
			"py/requirements.txt":     {"alpha==1.0", "beta==1.1", "gamma==1.0"},
			"py/requirements-dev.txt": {"alpha==1.0", "beta==1.1", "delta==1.0", "gamma==1.0"},
		}, ""},
		{"security of a transitive pin", of("gamma", false), map[string][]string{
			"py/requirements.txt":     {"alpha==1.0", "beta==1.0", "gamma==1.1"},
			"py/requirements-dev.txt": {"alpha==1.0", "beta==1.0", "delta==1.0", "gamma==1.1"},
		}, ""},
		{"lock file maintenance", of("", true), map[string][]string{
			"py/requirements.txt":     {"alpha==1.0", "beta==1.1", "gamma==1.1"},
			"py/requirements-dev.txt": {"alpha==1.0", "beta==1.1", "delta==1.0", "gamma==1.1"},
		}, ""},
	} {
		t.Run(tt.name, func(t *testing.T) {
			out := build(t, tt.ups)
			for f, want := range tt.want {
				if got := pins(out[f]); !slices.Equal(got, want) {
					t.Errorf("%s pins = %q, want %q", f, got, want)
				}
				if head(out[f]) != head(orig[f]) {
					t.Errorf("%s header changed: %q", f, head(out[f]))
				}
			}
			in, changed := out["py/requirements.in"]
			switch {
			case tt.in == "" && changed:
				t.Errorf("requirements.in changed: %s", in)
			case tt.in != "" && string(in) != tt.in:
				t.Errorf("requirements.in = %q, want %q", in, tt.in)
			}
			if len(out) != len(tt.want)+len(tt.in)/max(len(tt.in), 1) {
				t.Errorf("changed files: %d", len(out))
			}
		})
	}
}
