// Package docgen renders the generated reference documentation (docs/reference): the
// configuration reference from the JSON Schema, the CLI reference from the cobra command tree,
// the action reference from action.yml, and the managers and datasources reference from the
// refdoc facts next to their implementations. Output is deterministic.
package docgen

import (
	"fmt"
	"regexp"
	"strings"
	"unicode"

	"git.jakob-moeller.cloud/jakobmoellerdev/deps/internal/refdoc"
)

// Header is the first line of every generated markdown file.
const Header = "<!-- Code generated by `deps docs` (task docs); DO NOT EDIT. -->\n"

// Anchor returns the anchor GitHub, Gitea and Forgejo give a markdown heading: lowercase
// letters, digits, '-' and '_' are kept, spaces become '-', everything else (including
// backticks and punctuation) is dropped.
func Anchor(heading string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r) || r == '-' || r == '_':
			b.WriteRune(r)
		case r == ' ':
			b.WriteByte('-')
		}
	}
	return b.String()
}

// quotedRe finds a 'quoted' literal in plain text. Apostrophes inside words are not quotes: the
// opening quote follows a space, '(', '[' or the start, the closing one precedes a space,
// punctuation or the end.
var quotedRe = regexp.MustCompile(`(^|[\s(\[])'([^'\s][^']*?)'(?:[\s,.;:)\]]|$)`)

// PlainToMarkdown turns a plain-text description (struct tags and flag usages cannot hold
// backticks) into markdown: 'quoted' literals become code spans, and '<' and '*' outside code
// spans are escaped so <placeholders> and globs survive rendering. Existing code spans are
// kept.
func PlainToMarkdown(s string) string {
	var b strings.Builder
	parts := strings.Split(s, "`")
	for i, part := range parts {
		if i%2 == 1 {
			if i < len(parts)-1 { // inside an existing code span
				b.WriteString("`" + part + "`")
				continue
			}
			b.WriteByte('`') // an unbalanced backtick stays literal
		}
		// Matches are searched from just after each closing quote, so the character after it can
		// open the next literal ('a' 'b').
		for {
			m := quotedRe.FindStringSubmatchIndex(part)
			if m == nil {
				break
			}
			b.WriteString(escapeMarkdown(part[:m[3]]))
			b.WriteString(codeSpan(part[m[4]:m[5]]))
			part = part[m[5]+1:]
		}
		b.WriteString(escapeMarkdown(part))
	}
	return b.String()
}

var markdownEscaper = strings.NewReplacer(`<`, `\<`, `*`, `\*`)

func escapeMarkdown(s string) string { return markdownEscaper.Replace(s) }

// doc accumulates markdown and tracks heading anchors, so duplicate anchors (which would
// make links ambiguous) are reported instead of silently suffixed.
type doc struct {
	b       strings.Builder
	anchors map[string]bool
	err     error
}

func newDoc(title string) *doc {
	d := &doc{anchors: map[string]bool{}}
	d.b.WriteString(Header)
	d.b.WriteString("\n# " + title + "\n")
	return d
}

// heading writes a level-n heading; its anchor must be unique in the document.
func (d *doc) heading(level int, text string) {
	a := Anchor(text)
	if d.anchors[a] && d.err == nil {
		d.err = fmt.Errorf("duplicate heading anchor #%s (%q)", a, text)
	}
	d.anchors[a] = true
	d.b.WriteString("\n" + strings.Repeat("#", level) + " " + text + "\n")
}

// para writes a block of markdown followed by a blank line separator; empty text is skipped.
func (d *doc) para(text string) {
	if text = strings.TrimSpace(text); text != "" {
		d.b.WriteString("\n" + text + "\n")
	}
}

// list writes a bullet list.
func (d *doc) list(items []string) {
	if len(items) == 0 {
		return
	}
	d.b.WriteString("\n")
	for _, it := range items {
		d.b.WriteString("- " + indentRest(strings.TrimSpace(it), "  ") + "\n")
	}
}

// table writes a markdown table; cells are escaped for the table syntax.
func (d *doc) table(head []string, rows [][]string) {
	d.b.WriteString("\n|")
	for _, h := range head {
		d.b.WriteString(" " + h + " |")
	}
	d.b.WriteString("\n|" + strings.Repeat("---|", len(head)) + "\n")
	for _, r := range rows {
		d.b.WriteString("|")
		for _, c := range r {
			d.b.WriteString(" " + cell(c) + " |")
		}
		d.b.WriteString("\n")
	}
}

// code writes a fenced code block.
func (d *doc) code(lang, text string) {
	d.b.WriteString("\n```" + lang + "\n" + strings.TrimRight(text, "\n") + "\n```\n")
}

// section writes a refdoc section as a heading of level, its body and its items.
func (d *doc) section(level int, s refdoc.Section) {
	d.heading(level, s.Title)
	d.para(s.Body)
	d.list(s.Items)
}

func (d *doc) bytes() ([]byte, error) {
	if d.err != nil {
		return nil, d.err
	}
	return []byte(d.b.String()), nil
}

// cell makes text safe for a table cell: pipes are escaped (also inside code spans, which
// GitHub's tables require) and line breaks become spaces.
func cell(s string) string {
	s = strings.ReplaceAll(strings.TrimSpace(s), "\n", " ")
	var b strings.Builder
	for i := range len(s) {
		if s[i] == '|' && (i == 0 || s[i-1] != '\\') {
			b.WriteByte('\\')
		}
		b.WriteByte(s[i])
	}
	return b.String()
}

// indentRest indents every line after the first, so multi-line list items stay in the item.
func indentRest(s, indent string) string {
	return strings.ReplaceAll(s, "\n", "\n"+indent)
}

// codeSpan wraps s in backticks, using a longer fence when s contains backticks.
func codeSpan(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return "`` " + s + " ``"
}
